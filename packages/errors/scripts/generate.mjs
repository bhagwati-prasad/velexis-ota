#!/usr/bin/env node
// generate.mjs: generates the error catalogue of @velexis/errors from the `x-error-catalogue` of the OpenAPI
// documents (ADR-0006 "Checks in CI", conventions §6, task X-009).
//
// Usage (from packages/errors; `pnpm contracts:generate` at the repository root runs it through Turborepo, together
// with the generator of @velexis/api-types):
//   node scripts/generate.mjs                                # the documents of this repository into src/generated
//   node scripts/generate.mjs --root <dir> --out <dir>       # another copy of the repository layout (tests)
//
// It parses the documents with `yaml` (it does not read the generated types of @velexis/api-types) and writes
// src/generated/catalogue.ts: the `ErrorCode`, `OtaErrorCode` and `PlatformErrorCode` unions, the code lists and
// `ERROR_CATALOGUE` (code -> status, description, source). The platform document is read once it exists (the
// platform plan creates it in M1). Generation fails, and writes nothing, when a catalogue is malformed or when one
// code has different HTTP statuses in the two documents. The output is deterministic: no timestamps, no absolute
// paths, codes in document order. The generated file is committed and CI fails when a second run changes it, so
// never edit it by hand: change the document.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parse } from "yaml";

const PACKAGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const USAGE = "usage: node scripts/generate.mjs [--root <repository root>] [--out <dir>]";
const LOG_PREFIX = "contracts:generate (@velexis/errors)";

/** First line of every generated file. The tests look for it. */
const GENERATED_HEADER = "// Generated by scripts/generate.mjs — do not edit";

/**
 * The documents, relative to the repository root: the locations ADR-0006 fixes, the same files as the `apis` of
 * packages/api-types/redocly.yaml, which `contracts:lint` and the @velexis/api-types generator read.
 */
const DOCUMENTS = {
  ota: "ota/backend/openapi/velexis-ota-booking-api.openapi.yaml",
  platform: "platform/backend/openapi/velexis-platform-api.openapi.yaml",
};

/** Why the platform document may be missing (ADR-0006: the platform plan writes it in M1, PBE-005). */
const PLATFORM_PENDING = "the platform plan creates it in M1 (ADR-0006)";

/** The `code` pattern of the `Error` schema of the OTA document. A code is also a TypeScript identifier. */
const CODE_PATTERN = /^[A-Z][A-Z0-9_]+$/;

class GenerateError extends Error {}

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
const message = (err) => (err instanceof Error ? err.message : String(err));

function readOptions(argv) {
  try {
    const { values } = parseArgs({
      args: argv,
      options: { root: { type: "string" }, out: { type: "string" } },
      strict: true,
    });
    return {
      root: path.resolve(values.root ?? path.join(PACKAGE_DIR, "..", "..")),
      out: path.resolve(values.out ?? path.join(PACKAGE_DIR, "src", "generated")),
    };
  } catch (err) {
    throw new GenerateError(`${message(err)}\n${USAGE}`);
  }
}

function parseDocument(root, label) {
  const file = DOCUMENTS[label];
  let document;
  try {
    document = parse(readFileSync(path.join(root, file), "utf8"));
  } catch (err) {
    throw new GenerateError(`cannot parse the ${label} document ${file}: ${message(err)}`);
  }
  if (!isObject(document) || typeof document.openapi !== "string") {
    throw new GenerateError(`the ${label} document ${file} is not an OpenAPI 3 document`);
  }
  return document;
}

/**
 * The `x-error-catalogue` of one document as `{ code, status, description }` in document order. Every code must
 * match the `Error` schema's pattern, its `status` must be an HTTP error status and its `description` (the default
 * message of AppError) a non-empty string. Other keys of an entry are ignored. A repeated code is already refused
 * by the YAML parser (duplicate keys).
 */
function readCatalogue(document, label) {
  const where = `the ${label} document ${DOCUMENTS[label]}`;
  const catalogue = document["x-error-catalogue"];
  if (catalogue === undefined) {
    throw new GenerateError(`${where} has no "x-error-catalogue"`);
  }
  if (!isObject(catalogue) || Object.keys(catalogue).length === 0) {
    throw new GenerateError(`${where}: "x-error-catalogue" must map at least one error code to its entry`);
  }
  return Object.entries(catalogue).map(([code, entry]) => {
    const at = `${label} x-error-catalogue ${code}`;
    if (!CODE_PATTERN.test(code)) {
      throw new GenerateError(`${at}: a code must match ${CODE_PATTERN.source} (the Error schema's pattern)`);
    }
    if (!isObject(entry)) {
      throw new GenerateError(`${at}: the entry must be a mapping with "status" and "description"`);
    }
    const { status, description } = entry;
    if (!Number.isInteger(status) || status < 400 || status > 599) {
      throw new GenerateError(`${at}: "status" must be an HTTP error status, an integer from 400 to 599`);
    }
    if (typeof description !== "string" || description.trim() === "") {
      throw new GenerateError(`${at}: "description" must be a non-empty string`);
    }
    return { code, status, description };
  });
}

/**
 * One catalogue of both documents: the OTA codes first, then the platform-only codes, each in document order. A
 * code of both documents keeps the OTA entry (the platform API reuses the OTA codes, conventions §6) and must have
 * the same status in both, or generation fails with every conflicting code.
 */
function mergeCatalogues(ota, platform) {
  const entries = new Map(ota.map((entry) => [entry.code, { ...entry, source: "ota" }]));
  const conflicts = [];
  for (const entry of platform ?? []) {
    const known = entries.get(entry.code);
    if (known === undefined) {
      entries.set(entry.code, { ...entry, source: "platform" });
    } else if (known.status !== entry.status) {
      conflicts.push(
        `${entry.code} is ${known.status} in ${DOCUMENTS.ota} but ${entry.status} in ${DOCUMENTS.platform}`,
      );
    }
  }
  if (conflicts.length > 0) {
    throw new GenerateError(
      `a code must have the same HTTP status in both documents (conventions §6): ${conflicts.join("; ")}`,
    );
  }
  return [...entries.values()];
}

/** A union of string literal types, one per line, or `never` for no codes. */
function unionOf(codes) {
  return codes.length === 0
    ? " never;"
    : `\n${codes.map((code) => `  | ${JSON.stringify(code)}`).join("\n")};`;
}

/** A frozen array literal of codes, one per line. */
function listOf(codes) {
  return codes.length === 0
    ? "Object.freeze([])"
    : `Object.freeze([\n${codes.map((code) => `  ${JSON.stringify(code)},`).join("\n")}\n])`;
}

function catalogueFile({ ota, platform, merged }) {
  const otaCodes = ota.map((entry) => entry.code);
  const platformCodes = (platform ?? []).map((entry) => entry.code);
  const platformOnly = merged.filter((entry) => entry.source === "platform").length;
  const platformSource = platform
    ? `${DOCUMENTS.platform} (${platformCodes.length} codes, ${platformOnly} only there)`
    : `${DOCUMENTS.platform}, which does not exist yet: ${PLATFORM_PENDING}`;
  return [
    GENERATED_HEADER,
    `// Sources: ${DOCUMENTS.ota} (${otaCodes.length} codes)`,
    `//          ${platformSource}`,
    "// The error catalogue of both APIs, from the `x-error-catalogue` of each document (conventions §6). A new code",
    "// is added to its document first; `pnpm contracts:generate` then rewrites this file.",
    "",
    "/**",
    " * The document an entry comes from: `ota` for every code of the OTA catalogue (the platform API reuses those",
    " * codes with the same status), `platform` for a code that only the platform catalogue lists.",
    " */",
    'export type ErrorSource = "ota" | "platform";',
    "",
    "/** One code of the catalogue. */",
    "export interface ErrorCatalogueEntry {",
    "  /** The HTTP status of the code; the same in both documents (generation fails otherwise). */",
    "  readonly status: number;",
    "  /** The catalogue description: a generic message that is safe to show, and the default AppError message. */",
    "  readonly description: string;",
    "  /** The document the entry comes from. */",
    "  readonly source: ErrorSource;",
    "}",
    "",
    "/** Every code of the OTA document's `x-error-catalogue`, in document order. */",
    `export type OtaErrorCode =${unionOf(otaCodes)}`,
    "",
    "/** Every code of the platform document's `x-error-catalogue`; `never` while the document does not exist. */",
    `export type PlatformErrorCode =${unionOf(platformCodes)}`,
    "",
    "/** Every public error code of the two APIs: the only codes `new AppError(code)` accepts. */",
    "export type ErrorCode = OtaErrorCode | PlatformErrorCode;",
    "",
    "/** The codes of the OTA catalogue, in document order. */",
    `export const OTA_ERROR_CODES: readonly OtaErrorCode[] = ${listOf(otaCodes)};`,
    "",
    "/** The codes of the platform catalogue, in document order; empty while the document does not exist. */",
    `export const PLATFORM_ERROR_CODES: readonly PlatformErrorCode[] = ${listOf(platformCodes)};`,
    "",
    "/** Freezes every entry and the catalogue itself. */",
    "function freeze(",
    "  catalogue: Record<ErrorCode, ErrorCatalogueEntry>,",
    "): Readonly<Record<ErrorCode, ErrorCatalogueEntry>> {",
    "  for (const entry of Object.values(catalogue)) {",
    "    Object.freeze(entry);",
    "  }",
    "  return Object.freeze(catalogue);",
    "}",
    "",
    "/** Code -> status, description and source: the OTA codes, then the platform-only codes, in document order. */",
    "export const ERROR_CATALOGUE = freeze({",
    ...merged.map(
      ({ code, status, description, source }) =>
        `  ${code}: { status: ${status}, source: ${JSON.stringify(source)}, description: ${JSON.stringify(description)} },`,
    ),
    "});",
    "",
  ].join("\n");
}

/** Writes a file only when its content changes, and says whether it changed. */
function writeOutput(out, name, content) {
  const file = path.join(out, name);
  const unchanged = existsSync(file) && readFileSync(file, "utf8") === content;
  if (!unchanged) {
    mkdirSync(out, { recursive: true });
    writeFileSync(file, content);
  }
  console.log(`${LOG_PREFIX}: ${unchanged ? "unchanged" : "wrote"} ${name}`);
}

function main(argv) {
  const { root, out } = readOptions(argv);
  if (!existsSync(path.join(root, DOCUMENTS.ota))) {
    throw new GenerateError(`the OTA document ${DOCUMENTS.ota} does not exist`);
  }
  const platformExists = existsSync(path.join(root, DOCUMENTS.platform));
  if (!platformExists) {
    console.log(
      `${LOG_PREFIX}: "platform": ${DOCUMENTS.platform} does not exist yet; ${PLATFORM_PENDING}. ` +
        "PlatformErrorCode stays empty.",
    );
  }

  const ota = readCatalogue(parseDocument(root, "ota"), "ota");
  const platform = platformExists ? readCatalogue(parseDocument(root, "platform"), "platform") : null;
  const merged = mergeCatalogues(ota, platform);

  writeOutput(out, "catalogue.ts", catalogueFile({ ota, platform, merged }));
  console.log(
    `${LOG_PREFIX}: ${merged.length} error codes (${ota.length} OTA, ${platform?.length ?? 0} platform).`,
  );
}

try {
  main(process.argv.slice(2));
} catch (err) {
  if (!(err instanceof GenerateError)) {
    throw err;
  }
  console.error(`${LOG_PREFIX}: ${err.message}`);
  process.exitCode = 1;
}
