#!/usr/bin/env node
// codegen.mjs: generates the Kysely table types of @velexis/db with kysely-codegen (ADR-0005 Query layer item 2,
// task X-014).
//
// Usage (from packages/db; the root `pnpm db:codegen` runs the package's `codegen` script, which builds the package
// first because this script uses the runner of dist/ through `@velexis/db/migrate`):
//   node scripts/codegen.mjs                 # writes src/generated/{platform,reference,tenant}.ts
//   node scripts/codegen.mjs --out <dir>     # writes the three files elsewhere (the integration test)
//
// What it does:
//   1. As TEST_DATABASE_ADMIN_URL (role velexis_test_admin, LOGIN CREATEDB, member of velexis_migrator; read through
//      @velexis/config, so from the environment or a .env.local file) it creates the scratch database
//      `velexis_codegen_<pid>` with the database options and grants of deploy/postgres/bootstrap.sql, then runs the
//      in-database statements of bootstrap.sql (base schemas, default privileges) as velexis_migrator.
//   2. With the runner library: runMigrations for the platform and reference sets of platform/backend/migrations,
//      then migrateTenantSchema({ create: true }) for `tenant_template` with ota/backend/migrations/tenant, the way
//      provisioning creates a tenant schema (SET LOCAL ROLE velexis_provisioner). The runner connects as the admin
//      role, so the platform and reference tables belong to it instead of velexis_migrator; owners and grants are
//      not part of the types, and the database is dropped at the end.
//   3. kysely-codegen (Node API) once per schema: `platform.*` and `reference.*` keep their qualified names,
//      `tenant_template` is the default schema of its run, so tenant table names are unqualified.
//   4. Post-processing:
//      - kysely-codegen sorts with String#localeCompare, whose order depends on the machine's locale, so every
//        declaration and every interface member is sorted again by code unit;
//      - `Int8`, `Numeric` and `Timestamp` are set to the column types of the per-pool type parsers (ADR-0005
//        item 5): numeric and int8 select as `string`, timestamptz as `Date`; numeric is also written as a decimal
//        string only (conventions §1: money is never a number);
//      - any other helper declaration or import (a PostgreSQL enum, `interval`, `point`) fails the run, so a new
//        column type is mapped here deliberately instead of slipping through;
//      - kysely-codegen's `DB` interface becomes `PlatformDatabase`, `ReferenceDatabase` (plus the unqualified
//        `ReferenceTables`) or `TenantTables`, and tenant.ts adds `TenantDatabase`: the tenant tables plus the
//        reference tables, because a tenant transaction's search_path is `<schema>, reference`;
//      - a "do not edit" header replaces kysely-codegen's.
//   5. Drops the scratch database, also when a step fails (a plain DROP DATABASE, which stops autovacuum workers;
//      WITH (FORCE) only as a fallback), then writes each file only when its content changed.
//
// The output holds no timestamp, database name, version or local path, so two runs give identical files. CI runs
// `pnpm db:migrate && pnpm db:codegen` and fails on any diff under src/generated (X-019). Never edit the generated
// files: add a migration, run `pnpm db:codegen`, commit the result.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { defineConfig, env, loadDevEnvFiles } from "@velexis/config";
import { migrateTenantSchema, runMigrations, splitSqlStatements } from "@velexis/db/migrate";
import { Kysely, PostgresDialect as KyselyPostgresDialect } from "kysely";
import { generate, PostgresDialect } from "kysely-codegen";
import pg from "pg";

const PACKAGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO_DIR = path.resolve(PACKAGE_DIR, "..", "..");
const USAGE = "usage: node scripts/codegen.mjs [--out <dir>]";
const LOG_PREFIX = "db:codegen";

/** First line of every generated file. The unit tests look for it. */
const GENERATED_HEADER = "// Generated by scripts/codegen.mjs — do not edit.";

/** The tenant schema the tenant set is applied to; its tables stand for every `tenant_<key>` schema. */
const TEMPLATE_SCHEMA = "tenant_template";

/** The migration folders, relative to the repository root (ADR-0004, ADR-0005 Migrations item 2). */
const MIGRATIONS = {
  platform: "platform/backend/migrations/platform",
  reference: "platform/backend/migrations/reference",
  tenant: "ota/backend/migrations/tenant",
};

/**
 * The column types every Velexis pool returns (createTypeParsers, ADR-0005 item 5). The select type (first
 * argument) is what the parsers produce. Inserts and updates of int8 and timestamptz accept what node-postgres can
 * send; numeric takes a decimal string only, because money is never a JS number (conventions §1: compute with
 * decimal.js and write `toFixed(2)`).
 */
const CANONICAL_TYPES = {
  Int8: "export type Int8 = ColumnType<string, bigint | number | string, bigint | number | string>;",
  Numeric: "export type Numeric = ColumnType<string, string, string>;",
  Timestamp: "export type Timestamp = ColumnType<Date, Date | string, Date | string>;",
};

/** Helper declarations kysely-codegen may emit for the column types of the reference DDL. */
const KNOWN_HELPERS = new Set([
  ...Object.keys(CANONICAL_TYPES),
  "ArrayType",
  "ArrayTypeImpl",
  "Generated",
  "Json",
  "JsonArray",
  "JsonObject",
  "JsonPrimitive",
  "JsonValue",
]);

/** The only import kysely-codegen's output may have: anything else would be a dependency of @velexis/db. */
const KYSELY_IMPORT = 'import type { ColumnType } from "kysely";';

class CodegenError extends Error {}

const message = (err) => (err instanceof Error ? err.message : String(err));

/** Plain code-unit order: the same on every machine, whatever its locale. */
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function readOptions(argv) {
  try {
    const { values } = parseArgs({ args: argv, options: { out: { type: "string" } }, strict: true });
    return { out: path.resolve(values.out ?? path.join(PACKAGE_DIR, "src", "generated")) };
  } catch (err) {
    throw new CodegenError(`${message(err)}\n${USAGE}`);
  }
}

/** TEST_DATABASE_ADMIN_URL, never printed. */
function adminUrl() {
  loadDevEnvFiles({ appDir: PACKAGE_DIR });
  const config = defineConfig({
    TEST_DATABASE_ADMIN_URL: env.url({ protocols: ["postgres:", "postgresql:"] }),
  });
  return config.TEST_DATABASE_ADMIN_URL;
}

function withDatabase(url, database) {
  const parsed = new URL(url);
  parsed.pathname = `/${database}`;
  return parsed.toString();
}

async function withClient(url, fn) {
  const client = new pg.Client({ connectionString: url, application_name: "velexis-db-codegen" });
  await client.connect();
  try {
    return await fn(client);
  } finally {
    await client.end();
  }
}

/** The statements of bootstrap.sql that run inside the database (after `\connect :db_name`). */
function bootstrapDatabaseStatements() {
  const file = path.join(REPO_DIR, "deploy", "postgres", "bootstrap.sql");
  const script = readFileSync(file, "utf8");
  const connect = /^\\connect :db_name[ \t]*$/m.exec(script);
  if (connect === null) {
    throw new CodegenError("deploy/postgres/bootstrap.sql has no \\connect :db_name line");
  }
  const rest = script.slice(connect.index + connect[0].length);
  // Plain SQL only: a psql meta-command or variable would need psql.
  if (/^\s*\\/m.test(rest) || /:'?[a-z_]+'?/i.test(rest.replace(/--.*$/gm, "").replace(/::/g, ""))) {
    throw new CodegenError("deploy/postgres/bootstrap.sql after \\connect is no longer plain SQL");
  }
  return splitSqlStatements(rest);
}

/** SQLSTATE object_in_use: `DROP DATABASE` found other sessions in the database after waiting 5 s for them. */
const OBJECT_IN_USE = "55006";

/**
 * Drops the scratch database. Every connection of this script is closed by then, so a plain `DROP DATABASE`
 * comes first: PostgreSQL itself stops an autovacuum worker that is busy in the new database. `WITH (FORCE)` is
 * only the fallback for a session still open after PostgreSQL's 5 s wait: it cannot stop an autovacuum worker as
 * a role without pg_signal_backend ("permission denied to terminate process"), so it never goes first.
 */
async function dropScratchDatabase(admin, name) {
  const database = pg.escapeIdentifier(name);
  await withClient(admin, async (client) => {
    try {
      await client.query(`DROP DATABASE IF EXISTS ${database}`);
    } catch (err) {
      if (err?.code !== OBJECT_IN_USE) {
        throw err;
      }
      await client.query(`DROP DATABASE IF EXISTS ${database} WITH (FORCE)`);
    }
  });
}

/** Drops the scratch database after a failed step without hiding that step's error. */
async function dropAfterFailure(admin, name) {
  try {
    await dropScratchDatabase(admin, name);
  } catch (err) {
    console.error(`${LOG_PREFIX}: could not drop the scratch database ${name}: ${message(err)}`);
  }
}

/** Creates the scratch database like the database section of bootstrap.sql. */
async function createScratchDatabase(admin, name) {
  const database = pg.escapeIdentifier(name);
  await withClient(admin, async (client) => {
    await client.query(
      `CREATE DATABASE ${database} OWNER velexis_migrator ENCODING 'UTF8' ` +
        `LC_COLLATE 'C.UTF-8' LC_CTYPE 'C.UTF-8' TEMPLATE template0`,
    );
  });
  try {
    await withClient(admin, async (client) => {
      await client.query(`REVOKE ALL ON DATABASE ${database} FROM PUBLIC`);
      await client.query(
        `GRANT CONNECT, TEMPORARY ON DATABASE ${database} TO velexis_platform_app, velexis_ota_app`,
      );
      await client.query(`GRANT CONNECT, TEMPORARY, CREATE ON DATABASE ${database} TO velexis_provisioner`);
      await client.query(`GRANT ALL ON DATABASE ${database} TO velexis_migrator`);
    });
  } catch (err) {
    await dropAfterFailure(admin, name);
    throw err;
  }
}

/** Migrates the scratch database: bootstrap statements, the platform and reference sets, the tenant template. */
async function migrate(url) {
  const statements = bootstrapDatabaseStatements();
  await withClient(url, async (client) => {
    await client.query("BEGIN");
    await client.query("SET LOCAL ROLE velexis_migrator");
    for (const statement of statements) {
      await client.query(statement);
    }
    await client.query("COMMIT");
  });
  for (const set of ["platform", "reference"]) {
    const result = await runMigrations({ set, dir: path.join(REPO_DIR, MIGRATIONS[set]), url });
    if (!result.dirExists) {
      throw new CodegenError(`the ${set} migrations folder ${MIGRATIONS[set]} does not exist`);
    }
  }
  const tenant = await migrateTenantSchema({
    schema: TEMPLATE_SCHEMA,
    dir: path.join(REPO_DIR, MIGRATIONS.tenant),
    url,
    create: true,
  });
  if (!tenant.dirExists) {
    throw new CodegenError(`the tenant migrations folder ${MIGRATIONS.tenant} does not exist`);
  }
}

/** kysely-codegen's output for the tables of one schema (no file written, no header). */
async function introspect(url, schema, defaultSchemas) {
  const pool = new pg.Pool({ connectionString: url, max: 1, application_name: "velexis-db-codegen" });
  const db = new Kysely({ dialect: new KyselyPostgresDialect({ pool }) });
  try {
    const dialect = new PostgresDialect({ numericParser: "string", dateParser: "timestamp", defaultSchemas });
    return await generate({
      db,
      dialect,
      includePattern: `${schema}.*`,
      defaultSchemas,
      outFile: null,
      skipAutogeneratedFileComment: true,
    });
  } finally {
    await db.destroy();
  }
}

/**
 * Splits kysely-codegen's output into its imports, helper types and interfaces (members with their comments). Any
 * other shape fails, so the post-processing never edits text it does not understand.
 */
function parseOutput(source, schema) {
  const where = `kysely-codegen output for ${schema}`;
  const imports = [];
  const types = new Map();
  const interfaces = new Map();
  for (const block of source.trim().split(/\n{2,}/)) {
    const typeMatch = /^export type (\w+)\b/.exec(block);
    const interfaceMatch = /^export interface (\w+) \{(?:\n([\s\S]*)\n)?\}$/.exec(block);
    if (block.startsWith("import ")) {
      imports.push(block);
    } else if (typeMatch !== null) {
      types.set(typeMatch[1], block);
    } else if (interfaceMatch !== null) {
      interfaces.set(
        interfaceMatch[1],
        parseMembers(interfaceMatch[2] ?? "", `${where}, ${interfaceMatch[1]}`),
      );
    } else {
      throw new CodegenError(`${where}: unexpected declaration ${JSON.stringify(block.split("\n")[0])}`);
    }
  }
  return { imports, types, interfaces };
}

/** The members of an interface body: `{ key, lines }`, where `lines` are its JSDoc comment and its declaration. */
function parseMembers(body, where) {
  const members = [];
  let comment = [];
  for (const line of body === "" ? [] : body.split("\n")) {
    if (comment.length > 0 && !comment.at(-1).endsWith("*/")) {
      comment.push(line);
      continue;
    }
    if (line.startsWith("  /**")) {
      comment = [line];
      continue;
    }
    const member = /^ {2}("[^"]+"|[A-Za-z_$][\w$]*): .+;$/.exec(line);
    if (member === null) {
      throw new CodegenError(`${where}: unexpected line ${JSON.stringify(line)}`);
    }
    members.push({
      key: JSON.parse(member[1].startsWith('"') ? member[1] : `"${member[1]}"`),
      lines: [...comment, line],
    });
    comment = [];
  }
  if (comment.length > 0) {
    throw new CodegenError(`${where}: a comment without a member`);
  }
  return members.sort((a, b) => byCodeUnit(a.key, b.key));
}

/**
 * Checks and normalises one schema's output: one known import, known helpers only (the parser types set to
 * CANONICAL_TYPES), the `DB` interface with every key in the expected form.
 */
function normalise(source, { schema, qualified }) {
  const where = `kysely-codegen output for ${schema}`;
  const { imports, types, interfaces } = parseOutput(source, schema);
  const unexpectedImports = imports.filter((line) => line !== KYSELY_IMPORT);
  if (unexpectedImports.length > 0) {
    throw new CodegenError(
      `${where}: unexpected import ${JSON.stringify(unexpectedImports[0])}; map the column type in scripts/codegen.mjs`,
    );
  }
  for (const name of types.keys()) {
    if (!KNOWN_HELPERS.has(name)) {
      throw new CodegenError(`${where}: unexpected type ${name}; map its column type in scripts/codegen.mjs`);
    }
  }
  for (const [name, declaration] of Object.entries(CANONICAL_TYPES)) {
    if (types.has(name)) {
      types.set(name, declaration);
    }
  }
  const tables = interfaces.get("DB");
  if (tables === undefined || tables.length === 0) {
    throw new CodegenError(`${where}: no tables found`);
  }
  interfaces.delete("DB");
  for (const { key } of tables) {
    const valid = qualified
      ? key.startsWith(`${schema}.`) && !key.slice(schema.length + 1).includes(".")
      : !key.includes(".");
    if (!valid) {
      throw new CodegenError(
        `${where}: table ${JSON.stringify(key)} is not ${qualified ? `qualified as ${schema}.<table>` : "unqualified"}`,
      );
    }
  }
  return {
    imports,
    types: [...types.entries()].sort(([a], [b]) => byCodeUnit(a, b)).map(([, declaration]) => declaration),
    interfaces: [...interfaces.entries()].sort(([a], [b]) => byCodeUnit(a, b)),
    tables,
  };
}

function interfaceBlock(name, members, doc) {
  const body = members.flatMap((member) => member.lines);
  return [...doc, `export interface ${name} {`, ...body, "}"].join("\n");
}

/** One generated file: header, imports, helper types, row interfaces, then the database types. */
function renderFile({ header, imports, types, interfaces }, extraImports, databaseBlocks) {
  const blocks = [
    [GENERATED_HEADER, ...header].join("\n"),
    [...imports, ...extraImports].join("\n"),
    ...types,
    ...interfaces.map(([name, members]) => interfaceBlock(name, members, [])),
    ...databaseBlocks,
  ];
  return `${blocks.join("\n\n")}\n`;
}

const COLUMN_TYPES_NOTE = [
  "// Column types follow the type parsers of every Velexis pool (ADR-0005 item 5): numeric and int8 are strings,",
  "// timestamptz is a Date, json and jsonb are parsed. Numeric is written as a decimal string, never a number.",
];

function platformFile(output) {
  const header = [
    `// Source: ${MIGRATIONS.platform}, applied to a scratch database and introspected with kysely-codegen`,
    "// (`pnpm db:codegen`). Tables of the `platform` schema, by qualified name.",
    ...COLUMN_TYPES_NOTE,
  ];
  return renderFile(
    { header, ...output },
    [],
    [
      interfaceBlock("PlatformDatabase", output.tables, [
        "/**",
        " * The tables of the `platform` schema by qualified name (`platform.<table>`): the role default search_path is",
        " * `pg_catalog`, so platform tables are only reachable qualified. `createPlatformDb` uses",
        " * `PlatformDatabase & ReferenceDatabase` unless told otherwise.",
        " */",
      ]),
    ],
  );
}

function referenceFile(output) {
  const header = [
    `// Source: ${MIGRATIONS.reference}, applied to a scratch database and introspected with kysely-codegen`,
    "// (`pnpm db:codegen`). Tables of the `reference` schema, by qualified and by unqualified name.",
    ...COLUMN_TYPES_NOTE,
  ];
  const unqualified = output.tables.map(({ key, lines }) => {
    const name = key.slice("reference.".length);
    return { key: name, lines: lines.map((line) => line.replace(`"${key}":`, `${name}:`)) };
  });
  return renderFile(
    { header, ...output },
    [],
    [
      interfaceBlock("ReferenceDatabase", output.tables, [
        "/** The tables of the `reference` schema by qualified name (`reference.<table>`), reachable from every pool. */",
      ]),
      interfaceBlock(
        "ReferenceTables",
        unqualified.sort((a, b) => byCodeUnit(a.key, b.key)),
        [
          "/**",
          " * The same tables by unqualified name: inside `tenantTx` the search_path is `<schema>, reference`, so they",
          " * resolve without the schema unless a tenant table has the same name (`TenantDatabase`).",
          " */",
        ],
      ),
    ],
  );
}

function tenantFile(output) {
  const header = [
    `// Source: ${MIGRATIONS.tenant}, applied to the scratch schema ${TEMPLATE_SCHEMA} and introspected with`,
    "// kysely-codegen (`pnpm db:codegen`). Tables of every tenant schema, by unqualified name (ADR-0004: tenant SQL",
    "// is never schema-qualified; tenantTx sets the search_path).",
    ...COLUMN_TYPES_NOTE,
  ];
  return renderFile(
    { header, ...output },
    ['import type { ReferenceDatabase, ReferenceTables } from "./reference.js";'],
    [
      interfaceBlock("TenantTables", output.tables, [
        "/** The tables of a tenant schema (`tenant_<key>`) by unqualified name. */",
      ]),
      [
        "/**",
        " * Everything a `tenantTx` transaction reaches. Its search_path is `<schema>, reference`, so the tenant tables",
        " * and the reference tables resolve unqualified, and a tenant table shadows a reference table of the same name",
        " * (`schema_migrations` is the tenant's ledger); `reference.<table>` resolves qualified. Platform tables are not",
        " * here: they are read through `createPlatformDb`, never inside a tenant transaction. `createTenantDb` uses this",
        " * type unless told otherwise.",
        " */",
        "export type TenantDatabase = TenantTables & Omit<ReferenceTables, keyof TenantTables> & ReferenceDatabase;",
      ].join("\n"),
    ],
  );
}

/** Writes a file only when its content changes, and says whether it changed. */
function writeOutput(out, name, content) {
  const file = path.join(out, name);
  const unchanged = existsSync(file) && readFileSync(file, "utf8") === content;
  if (!unchanged) {
    mkdirSync(out, { recursive: true });
    writeFileSync(file, content);
  }
  console.log(`${LOG_PREFIX}: ${unchanged ? "unchanged" : "wrote"} ${name}`);
}

async function main(argv) {
  const { out } = readOptions(argv);
  const admin = adminUrl();
  const name = `velexis_codegen_${process.pid}`;
  await createScratchDatabase(admin, name);
  let files;
  try {
    const url = withDatabase(admin, name);
    await migrate(url);
    const platform = normalise(await introspect(url, "platform", undefined), {
      schema: "platform",
      qualified: true,
    });
    const reference = normalise(await introspect(url, "reference", undefined), {
      schema: "reference",
      qualified: true,
    });
    const tenant = normalise(await introspect(url, TEMPLATE_SCHEMA, [TEMPLATE_SCHEMA]), {
      schema: TEMPLATE_SCHEMA,
      qualified: false,
    });
    files = [
      ["platform.ts", platformFile(platform), platform.tables.length],
      ["reference.ts", referenceFile(reference), reference.tables.length],
      ["tenant.ts", tenantFile(tenant), tenant.tables.length],
    ];
  } catch (err) {
    await dropAfterFailure(admin, name);
    throw err;
  }
  try {
    await dropScratchDatabase(admin, name);
  } catch (err) {
    throw new CodegenError(
      `could not drop the scratch database ${name}, so nothing was written: ${message(err)}. ` +
        `Drop it as TEST_DATABASE_ADMIN_URL (DROP DATABASE ${name}) and run pnpm db:codegen again.`,
    );
  }
  for (const [file, content] of files) {
    writeOutput(out, file, content);
  }
  console.log(`${LOG_PREFIX}: ${files.map(([file, , tables]) => `${tables} tables in ${file}`).join(", ")}.`);
}

try {
  await main(process.argv.slice(2));
} catch (err) {
  if (!(err instanceof CodegenError)) {
    throw err;
  }
  console.error(`${LOG_PREFIX}: ${err.message}`);
  process.exitCode = 1;
}
