// The generated table types (X-014; ADR-0005 Query layer item 2). Two halves:
//   - compile time: `pnpm typecheck` (tsc --noEmit over src/) checks the default type parameters of createTenantDb
//     and createPlatformDb, every `expectTypeOf` and every `// @ts-expect-error` below (an expected error that no
//     longer happens fails the type check);
//   - run time: Vitest runs the same queries against a recording fake pool, and reads src/generated next to the
//     baseline migrations (header, code-unit order, numeric columns).
import { readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type pg from "pg";
import { describe, expect, expectTypeOf, it } from "vitest";
import type { TenantTables } from "./generated/tenant.js";
import {
  createPlatformDb,
  createTenantDb,
  tenantTx,
  type Insertable,
  type Kysely,
  type PlatformDatabase,
  type ReferenceDatabase,
  type Selectable,
  type TenantDatabase,
  type TenantDb,
  type Updateable,
} from "./index.js";

const PACKAGE_DIR = resolve(__dirname, "..");
const REPO = resolve(PACKAGE_DIR, "..", "..");
const GENERATED_DIR = join(PACKAGE_DIR, "src", "generated");
const GENERATED_HEADER = "// Generated by scripts/codegen.mjs — do not edit.";

/** The generated files, the baseline each comes from, and the name of its database interface. */
const SCHEMAS = [
  {
    file: "platform.ts",
    baseline: "platform/backend/migrations/platform/0001_baseline.sql",
    database: "PlatformDatabase",
  },
  {
    file: "reference.ts",
    baseline: "platform/backend/migrations/reference/0001_baseline.sql",
    database: "ReferenceDatabase",
  },
  {
    file: "tenant.ts",
    baseline: "ota/backend/migrations/tenant/0001_baseline.sql",
    database: "TenantTables",
  },
] as const;

/** A pool with one fake connection that records every statement and answers the leak guard query. */
function fakePool() {
  const statements: string[] = [];
  const client = {
    query: (text: string) => {
      const sql = text.replace(/\s+/g, " ").trim();
      statements.push(sql);
      const rows = sql.includes("pg_settings")
        ? [{ search_path: "pg_catalog", role_default: "pg_catalog" }]
        : [];
      return Promise.resolve({ command: "SELECT", rowCount: rows.length, rows });
    },
    release: () => undefined,
  };
  const pool = {
    connect: () => Promise.resolve(client),
    end: () => Promise.resolve(),
  } as unknown as pg.Pool;
  return { pool, statements };
}

const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const sorted = (values: readonly string[]): string[] => [...values].sort(byCodeUnit);
const generated = (file: string): string => readFileSync(join(GENERATED_DIR, file), "utf8");

/** The members of `export interface <name> { … }` in `source`: key and type, comments dropped. */
function interfaceMembers(source: string, name: string): Map<string, string> {
  const block = new RegExp(`^export interface ${name} \\{\\n([\\s\\S]*?)\\n\\}$`, "m").exec(source);
  if (block?.[1] === undefined) {
    throw new Error(`no interface ${name}`);
  }
  const members = new Map<string, string>();
  for (const line of block[1].split("\n")) {
    const member = /^ {2}"?([\w.]+)"?: (.+);$/.exec(line);
    if (member?.[1] !== undefined && member[2] !== undefined) {
      members.set(member[1], member[2]);
    }
  }
  return members;
}

const CREATE_TABLE = /^CREATE TABLE (?:IF NOT EXISTS )?([a-z_.]+) \($/;
const baseline = (path: string): string => readFileSync(join(REPO, path), "utf8");

/** The tables of a baseline, as its `CREATE TABLE` statements name them. */
function baselineTables(ddl: string): string[] {
  return ddl.split("\n").flatMap((line) => CREATE_TABLE.exec(line)?.[1] ?? []);
}

/** The `numeric` columns of each `CREATE TABLE` of a baseline: `[table, column, sql type]`. */
function numericColumns(ddl: string): Array<[string, string, string]> {
  const columns: Array<[string, string, string]> = [];
  let table: string | undefined;
  for (const line of ddl.split("\n")) {
    const create = CREATE_TABLE.exec(line);
    if (create?.[1] !== undefined) {
      table = create[1];
    } else if (line.startsWith(")")) {
      table = undefined;
    } else if (table !== undefined) {
      const column = /^\s+([a-z_][a-z0-9_]*)\s+(numeric(?:\(\d+,\s*\d+\))?)[\s,]/.exec(line);
      if (column?.[1] !== undefined && column[2] !== undefined) {
        columns.push([table, column[1], column[2]]);
      }
    }
  }
  return columns;
}

describe("TenantDatabase: the default of createTenantDb", () => {
  it("[X-014 AC2] inside tenantTx, trx.selectFrom('bookings') compiles and trx.selectFrom('tenants') does not", async () => {
    const fake = fakePool();
    const tenants = createTenantDb(fake.pool, { appEnv: "test" });
    expectTypeOf(tenants).toEqualTypeOf<TenantDb<TenantDatabase>>();

    const platformSql = await tenantTx(tenants, "tenant_acme", async (trx) => {
      const booking = await trx
        .selectFrom("bookings")
        .select(["id", "total_amount", "created_at"])
        .where("id", "=", "bkg_1")
        .executeTakeFirst();
      expectTypeOf(booking).toEqualTypeOf<
        { id: string; total_amount: string; created_at: Date } | undefined
      >();
      // Platform tables are not part of a tenant transaction, by either name.
      // @ts-expect-error -- "tenants" is a platform table, not a tenant table
      const unqualified = trx.selectFrom("tenants").selectAll().compile().sql;
      // @ts-expect-error -- platform tables are read through createPlatformDb, never inside tenantTx
      const qualified = trx.selectFrom("platform.tenants").selectAll().compile().sql;
      return [unqualified, qualified];
    });

    // The tenant table is unqualified: the transaction's search_path names the schema.
    expect(fake.statements).toContain(
      'select "id", "total_amount", "created_at" from "bookings" where "id" = $1',
    );
    expect(platformSql).toEqual(['select * from "tenants"', 'select * from "platform"."tenants"']);
  });

  it("[X-014 AC2] reference tables resolve unqualified and as reference.<table> inside tenantTx", async () => {
    const fake = fakePool();
    const tenants = createTenantDb(fake.pool, { appEnv: "test" });

    await tenantTx(tenants, "tenant_acme", async (trx) => {
      const airport = await trx
        .selectFrom("airports")
        .select(["iata_code", "latitude"])
        .where("iata_code", "=", "LHR")
        .executeTakeFirst();
      expectTypeOf(airport).toEqualTypeOf<{ iata_code: string; latitude: string | null } | undefined>();
      const currencies = await trx
        .selectFrom("reference.currencies")
        .select(["code", "minor_units"])
        .execute();
      expectTypeOf(currencies).toEqualTypeOf<Array<{ code: string; minor_units: number }>>();
    });

    expect(fake.statements).toContain(
      'select "iata_code", "latitude" from "airports" where "iata_code" = $1',
    );
    expect(fake.statements).toContain('select "code", "minor_units" from "reference"."currencies"');
  });

  it("has every table of the tenant baseline, unqualified, and no platform table", () => {
    const tables = [...interfaceMembers(generated("tenant.ts"), "TenantTables").keys()];
    const created = baselineTables(baseline("ota/backend/migrations/tenant/0001_baseline.sql"));
    expect(created).toHaveLength(42); // the ledger schema_migrations included
    expect(tables).toEqual(expect.arrayContaining(created));
    expect(tables.filter((table) => !/^[a-z_]+$/.test(table))).toEqual([]);
    expectTypeOf<"bookings">().toMatchTypeOf<keyof TenantTables>();
    expectTypeOf<"airports">().toMatchTypeOf<keyof TenantDatabase>();
    expectTypeOf<"reference.airports">().toMatchTypeOf<keyof TenantDatabase>();
    expectTypeOf<"tenants">().not.toMatchTypeOf<keyof TenantDatabase>();
    expectTypeOf<"platform.tenants">().not.toMatchTypeOf<keyof TenantDatabase>();
  });
});

describe("PlatformDatabase & ReferenceDatabase: the default of createPlatformDb", () => {
  it("reaches platform.* and reference.* by qualified name, and no tenant table", () => {
    const fake = fakePool();
    const db = createPlatformDb(fake.pool);
    expectTypeOf(db).toEqualTypeOf<Kysely<PlatformDatabase & ReferenceDatabase>>();

    const tenant = db.selectFrom("platform.tenants").select(["id", "schema_name"]).where("key", "=", "acme");
    expectTypeOf(tenant.executeTakeFirst()).resolves.toEqualTypeOf<
      { id: string; schema_name: string | null } | undefined
    >();
    expect(tenant.compile().sql).toBe(
      'select "id", "schema_name" from "platform"."tenants" where "key" = $1',
    );
    expect(db.selectFrom("reference.airports").select("name").compile().sql).toBe(
      'select "name" from "reference"."airports"',
    );
    // @ts-expect-error -- tenant tables are reachable only through tenantTx
    expect(db.selectFrom("bookings").selectAll().compile().sql).toBe('select * from "bookings"');
    // @ts-expect-error -- platform tables are always qualified: the role default search_path is pg_catalog
    expect(db.selectFrom("tenants").selectAll().compile().sql).toBe('select * from "tenants"');
  });
});

describe("column types follow the type parsers", () => {
  it("[X-014 AC3] numeric(12,2) columns are typed string", () => {
    expectTypeOf<Selectable<TenantDatabase["bookings"]>["total_amount"]>().toEqualTypeOf<string>();
    expectTypeOf<Selectable<TenantDatabase["bookings"]>["net_base_amount"]>().toEqualTypeOf<string | null>();
    expectTypeOf<Selectable<TenantDatabase["priced_offers"]>["selling_total"]>().toEqualTypeOf<string>();
    expectTypeOf<Selectable<PlatformDatabase["platform.plans"]>["monthly_price"]>().toEqualTypeOf<string>();
    expectTypeOf<Selectable<PlatformDatabase["platform.plans"]>["annual_price"]>().toEqualTypeOf<
      string | null
    >();
    expectTypeOf<Selectable<PlatformDatabase["platform.invoices"]>["total"]>().toEqualTypeOf<string>();
    // Writes take a decimal string only: money is never a JS number (conventions §1; decimal.js, then toFixed).
    expectTypeOf<Insertable<TenantDatabase["bookings"]>["total_amount"]>().toEqualTypeOf<string>();
    expectTypeOf<number>().not.toMatchTypeOf<Insertable<TenantDatabase["bookings"]>["total_amount"]>();
    expectTypeOf<number>().not.toMatchTypeOf<
      NonNullable<Updateable<PlatformDatabase["platform.plans"]>["monthly_price"]>
    >();

    // Every generated file reads and writes Numeric as a string, and every numeric column of the baselines is
    // Numeric.
    const checked: string[] = [];
    for (const { file, baseline: path, database } of SCHEMAS) {
      const source = generated(file);
      if (source.includes("export type Numeric")) {
        expect(source).toContain("export type Numeric = ColumnType<string, string, string>;");
      }
      const tables = interfaceMembers(source, database);
      for (const [table, column, sqlType] of numericColumns(baseline(path))) {
        const rowType = tables.get(table);
        expect(rowType, `${file}: ${table}`).toBeDefined();
        const columnType = interfaceMembers(source, rowType ?? "").get(column);
        expect(
          ["Numeric", "Numeric | null", "Generated<Numeric>"],
          `${table}.${column} ${sqlType} is ${columnType}`,
        ).toContain(columnType);
        checked.push(sqlType);
      }
    }
    // 8 platform and 47 tenant numeric(12,2) money columns; 2 numeric(7,4) percentages and 1 numeric(12,4) score
    // in tenant; 4 numeric(9,6) coordinates in reference.
    expect(checked.filter((sqlType) => sqlType === "numeric(12,2)")).toHaveLength(55);
    expect(checked).toHaveLength(62);
  });

  it("int8 is a string and timestamptz a Date", () => {
    expectTypeOf<Selectable<TenantDatabase["customer_data_exports"]>["size_bytes"]>().toEqualTypeOf<
      string | null
    >();
    expectTypeOf<Selectable<PlatformDatabase["platform.platform_audit_log"]>["id"]>().toEqualTypeOf<string>();
    expectTypeOf<Selectable<TenantDatabase["bookings"]>["created_at"]>().toEqualTypeOf<Date>();
    expectTypeOf<Selectable<TenantDatabase["bookings"]>["cancelled_at"]>().toEqualTypeOf<Date | null>();
    for (const { file } of SCHEMAS) {
      const source = generated(file);
      expect(source).toContain("export type Timestamp = ColumnType<Date, Date | string, Date | string>;");
      if (source.includes("export type Int8")) {
        expect(source).toContain(
          "export type Int8 = ColumnType<string, bigint | number | string, bigint | number | string>;",
        );
      }
    }
  });
});

describe("the generated files", () => {
  it.each(SCHEMAS)(
    "[X-014 AC1] $file has the do-not-edit header and is sorted by code unit, without run-specific text",
    ({ file, database }) => {
      const source = generated(file);
      expect(source.split("\n")[0]).toBe(GENERATED_HEADER);
      expect(source.endsWith("}\n") || source.endsWith(";\n")).toBe(true);
      // No scratch database name (it holds the process id), no local path, no timestamp.
      expect(source).not.toMatch(/velexis_codegen|\/home\/|\/tmp\/|\/Users\/|[A-Z]:\\|\d{4}-\d{2}-\d{2}T/);

      const types = [...source.matchAll(/^export type (\w+)/gm)].map((match) => match[1] ?? "");
      const helperTypes = types.filter((name) => name !== "TenantDatabase");
      expect(helperTypes).toEqual(sorted(helperTypes));
      const interfaces = [...source.matchAll(/^export interface (\w+)/gm)].map((match) => match[1] ?? "");
      const rowTypes = interfaces.filter((name) => !/(Database|Tables)$/.test(name));
      expect(rowTypes).toEqual(sorted(rowTypes));
      for (const name of interfaces) {
        const keys = [...interfaceMembers(source, name).keys()];
        expect(keys, name).toEqual(sorted(keys));
      }
      expect(interfaces).toContain(database);
    },
  );

  it("names platform tables platform.<table> and reference tables reference.<table>, each baseline table included", () => {
    const platform = [...interfaceMembers(generated("platform.ts"), "PlatformDatabase").keys()];
    const platformBaseline = baselineTables(
      baseline("platform/backend/migrations/platform/0001_baseline.sql"),
    );
    expect(platformBaseline).toHaveLength(16);
    expect(platform).toEqual(expect.arrayContaining([...platformBaseline, "platform.schema_migrations"]));
    expect(platform.every((table) => /^platform\.[a-z_]+$/.test(table))).toBe(true);
    const reference = [...interfaceMembers(generated("reference.ts"), "ReferenceDatabase").keys()];
    const referenceBaseline = baselineTables(
      baseline("platform/backend/migrations/reference/0001_baseline.sql"),
    );
    expect(referenceBaseline).toHaveLength(7);
    expect(reference).toEqual(expect.arrayContaining([...referenceBaseline, "reference.schema_migrations"]));
    expect(reference.every((table) => /^reference\.[a-z_]+$/.test(table))).toBe(true);
    const unqualified = [...interfaceMembers(generated("reference.ts"), "ReferenceTables").keys()];
    expect(unqualified).toEqual(reference.map((table) => table.slice("reference.".length)));
  });
});
