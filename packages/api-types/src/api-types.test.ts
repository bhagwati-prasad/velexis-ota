interface Run {
  code: number | null;
  stdout: string;
  stderr: string;
}

function runGenerate(args: readonly string[]): Promise<Run> {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [SCRIPT, ...args], {
      cwd: PACKAGE_DIR,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8").on("data", (chunk: string) => {
      stdout += chunk;
    });
    child.stderr.setEncoding("utf8").on("data", (chunk: string) => {
      stderr += chunk;
    });
    child.on("error", reject);
    child.on("close", (code) => {
      resolve({ code, stdout, stderr });
    });
  });
}

type GeneratedFiles = Record<(typeof GENERATED_FILES)[number], string>;

function readFiles(dir: string): GeneratedFiles {
  const [ota, platform, operations] = GENERATED_FILES.map((name) => readFileSync(join(dir, name), "utf8"));
  return { "ota.ts": ota!, "platform.ts": platform!, "operations.ts": operations! };
}

type OpenApiOperation = Record<string, unknown>;
interface OpenApiDocument {
  paths: Record<string, Record<string, unknown>>;
}

/** Every operation of a parsed OpenAPI document with its method and path. */
function documentOperations(
  document: OpenApiDocument,
): Array<{ method: HttpMethod; path: string; operation: OpenApiOperation }> {
  return Object.entries(document.paths).flatMap(([path, item]) =>
    HTTP_METHODS.filter((method) => item[method] !== undefined).map((method) => ({
      method,
      path,
      operation: item[method] as OpenApiOperation,
    })),
  );
}

function readDocument(file: string): OpenApiDocument {
  return parse(readFileSync(file, "utf8")) as OpenApiDocument;
}

