describe("@velexis/api-types/operations", () => {
  let frozen: OpenApiDocument;
  let working: OpenApiDocument;
  beforeAll(() => {
    frozen = readDocument(FROZEN_OPENAPI);
    working = readDocument(join(REPO_ROOT, OTA_PATH));
  });

  it("lists every operation of the frozen contract with its method, path and x-sdk-method [X-008 AC2]", () => {
    const contract = documentOperations(frozen);
    expect(contract).toHaveLength(FROZEN_OPERATION_COUNT);
    const byId = new Map<string, ApiOperation>(otaOperations.map((op) => [op.operationId, op]));

    const missing = contract.filter(({ operation }) => !byId.has(String(operation["operationId"])));
    expect(missing).toEqual([]);
    for (const { method, path, operation } of contract) {
      expect(byId.get(String(operation["operationId"]))).toMatchObject({
        method,
        path,
        sdkMethod: operation["x-sdk-method"],
      });
    }
    // Spec-first tasks may add operations, never remove one.
    expect(otaOperations.length).toBeGreaterThanOrEqual(FROZEN_OPERATION_COUNT);
  });

  it("gives every operation without x-internal an sdkMethod [X-008 AC2]", () => {
    // Plain-URL operations marked x-sdk-exclude (file downloads, public assets) have no SDK method either
    // (ota/docs/api-changes.md §1); none exists before OBE-054.
    const sdkExcluded = new Set(
      documentOperations(working)
        .filter(({ operation }) => operation["x-sdk-exclude"] === true)
        .map(({ operation }) => String(operation["operationId"])),
    );

    const withoutSdkMethod = otaOperations.filter(
      (op) => !op.internal && !sdkExcluded.has(op.operationId) && op.sdkMethod === null,
    );

    expect(withoutSdkMethod).toEqual([]);
    expect(otaOperations.filter((op) => !op.internal).length).toBeGreaterThanOrEqual(FROZEN_OPERATION_COUNT);
  });

  it("matches the working documents operation by operation, in document order", () => {
    const expected = documentOperations(working).map(({ method, path, operation }) => ({
      operationId: operation["operationId"],
      method,
      path,
      sdkMethod: operation["x-sdk-method"] ?? null,
      scope: operation["x-scope"] ?? null,
      tags: operation["tags"] ?? [],
      internal: operation["x-internal"] === true,
    }));
    // A subset match per entry, so fields added to the index later (OBE-009) do not break it.
    expect(otaOperations).toMatchObject(expected);

    const platformDocument = join(REPO_ROOT, PLATFORM_PATH);
    const platformIds = existsSync(platformDocument)
      ? documentOperations(readDocument(platformDocument)).map(({ operation }) => operation["operationId"])
      : [];
    expect(platformOperations.map((op) => op.operationId)).toEqual(platformIds);
  });

  it("is frozen, entries and tags included", () => {
    expect(Object.isFrozen(otaOperations)).toBe(true);
    expect(Object.isFrozen(platformOperations)).toBe(true);
    for (const op of [...otaOperations, ...platformOperations]) {
      expect(Object.isFrozen(op)).toBe(true);
      expect(Object.isFrozen(op.tags)).toBe(true);
    }
    const first = otaOperations[0]!;
    expect(() => {
      (first as { path: string }).path = "/changed";
    }).toThrow(TypeError);
  });

  it("types operationId with the keys of the generated operations", () => {
    const id: OtaOperationId = "getStorefront";
    const fromIndex: OtaOperationId | undefined = otaOperations[0]?.operationId;
    // @ts-expect-error an operationId that the OTA document does not have does not compile
    const unknownId: OtaOperationId = "getStorefrontt";
    const platformIds: readonly PlatformOperationId[] = platformOperations.map((op) => op.operationId);
    expect([id, fromIndex, unknownId]).toEqual(["getStorefront", "getStorefront", "getStorefrontt"]);
    expect(platformIds).toHaveLength(platformOperations.length);
  });
});

