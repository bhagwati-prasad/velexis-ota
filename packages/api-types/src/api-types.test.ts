/**
 * Writes a scratch repository with packages/api-types/redocly.yaml (a verbatim copy) and the given documents at
 * their repository paths. Returns the config path for `--config` and an output folder for `--out`.
 */
function makeTree(
  name: string,
  documents: { ota?: string; platform?: string },
): { config: string; out: string } {
  const root = join(scratch, name);
  const config = join(root, "packages", "api-types", "redocly.yaml");
  mkdirSync(dirname(config), { recursive: true });
  copyFileSync(CONFIG, config);
  for (const [path, content] of [
    [OTA_PATH, documents.ota],
    [PLATFORM_PATH, documents.platform],
  ] as const) {
    if (content !== undefined) {
      mkdirSync(dirname(join(root, path)), { recursive: true });
      writeFileSync(join(root, path), content);
    }
  }
  return { config, out: join(root, "packages", "api-types", "src", "generated") };
}

interface SmallOperation {
  path: string;
  method?: HttpMethod;
  lines: readonly string[];
}

/** A small, valid OpenAPI 3.1 document; each operation gives its own lines below the method. */
function smallDocument(title: string, ops: readonly SmallOperation[]): string {
  return [
    "openapi: 3.1.0",
    "info:",
    `  title: ${title}`,
    "  version: 1.0.0",
    "paths:",
    ...ops.flatMap((op) => [
      `  ${op.path}:`,
      `    ${op.method ?? "get"}:`,
      ...op.lines.map((line) => `      ${line}`),
      "      responses:",
      '        "200":',
      "          description: OK",
      "          content:",
      "            application/json:",
      "              schema:",
      '                $ref: "#/components/schemas/Thing"',
    ]),
    "components:",
    "  schemas:",
    "    Thing:",
    "      type: object",
    "      required: [id]",
    "      properties:",
    "        id:",
    "          type: string",
    "",
  ].join("\n");
}

