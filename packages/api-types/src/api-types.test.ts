/** A TypeScript program over the package sources, the SDK contract and in-memory snippets in src/. */
function createProgram(snippets: ReadonlyMap<string, string>): ts.Program {
  const options: ts.CompilerOptions = {
    strict: true,
    exactOptionalPropertyTypes: true,
    noUncheckedIndexedAccess: true,
    noEmit: true,
    // Declaration files are checked too, so a contract file that cannot resolve @velexis/api-types reports it.
    skipLibCheck: false,
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    types: ["node"],
    // shared.d.ts uses fetch types (RequestCache) of the DOM library, as the SDK does.
    lib: ["lib.es2023.d.ts", "lib.dom.d.ts"],
    // The module name the SDK contract imports, resolved to this package's sources.
    paths: { "@velexis/api-types": [join(PACKAGE_DIR, "src", "index.ts")] },
  };
  const host = ts.createCompilerHost(options);
  const getSourceFile = host.getSourceFile.bind(host);
  const fileExists = host.fileExists.bind(host);
  host.getSourceFile = (fileName, languageVersion, ...rest) => {
    const text = snippets.get(fileName);
    return text === undefined
      ? getSourceFile(fileName, languageVersion, ...rest)
      : ts.createSourceFile(fileName, text, languageVersion);
  };
  host.fileExists = (fileName) => snippets.has(fileName) || fileExists(fileName);
  return ts.createProgram({
    rootNames: [
      join(PACKAGE_DIR, "src", "index.ts"),
      join(PACKAGE_DIR, "src", "platform.ts"),
      SDK_CONTRACT_TYPES,
      SDK_CONTRACT_SHARED,
      ...snippets.keys(),
    ],
    options,
    host,
  });
}

function diagnosticsOf(program: ts.Program, file: string): string[] {
  const sourceFile = program.getSourceFile(file);
  if (sourceFile === undefined) {
    throw new Error(`${file} is not part of the program`);
  }
  return [...program.getSyntacticDiagnostics(sourceFile), ...program.getSemanticDiagnostics(sourceFile)].map(
    (diagnostic) => `TS${diagnostic.code}: ${ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")}`,
  );
}

interface GeneratedIndex {
  otaOperations: readonly ApiOperation[];
  platformOperations: readonly ApiOperation[];
}

/**
 * The index of a generated operations.ts, run after TypeScript strips its types. It imports types only, so it
 * must not need `require` at run time.
 */
function loadIndex(source: string): GeneratedIndex {
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  const exports: Partial<GeneratedIndex> = {};
  const run = runInThisContext(`(function (exports, require) {\n${outputText}\n})`) as (
    exports: Partial<GeneratedIndex>,
    require: (id: string) => never,
  ) => void;
  run(exports, (id) => {
    throw new Error(`the operations index must not import ${id} at run time`);
  });
  if (exports.otaOperations === undefined || exports.platformOperations === undefined) {
    throw new Error("the operations index does not export otaOperations and platformOperations");
  }
  return { otaOperations: exports.otaOperations, platformOperations: exports.platformOperations };
}

/** The TypeScript errors of a folder of generated files (operations.ts imports ota.ts and platform.ts). */
function compileGenerated(dir: string): string[] {
  const program = ts.createProgram({
    rootNames: GENERATED_FILES.map((name) => join(dir, name)),
    options: {
      strict: true,
      exactOptionalPropertyTypes: true,
      noUncheckedIndexedAccess: true,
      noEmit: true,
      skipLibCheck: true,
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.NodeNext,
      moduleResolution: ts.ModuleResolutionKind.NodeNext,
      types: [],
      lib: ["lib.es2023.d.ts"],
    },
  });
  return ts
    .getPreEmitDiagnostics(program)
    .map(
      (diagnostic) =>
        `TS${diagnostic.code}: ${ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")}`,
    );
}

/** The type of the export `name` of a module, following re-exports (`export type { … } from`). */
function exportedType(program: ts.Program, file: string, name: string): ts.Type {
  const checker = program.getTypeChecker();
  const sourceFile = program.getSourceFile(file);
  const moduleSymbol = sourceFile === undefined ? undefined : checker.getSymbolAtLocation(sourceFile);
  let symbol =
    moduleSymbol && checker.getExportsOfModule(moduleSymbol).find((exported) => exported.name === name);
  if (symbol === undefined) {
    throw new Error(`${file} does not export ${name}`);
  }
  if (symbol.flags & ts.SymbolFlags.Alias) {
    symbol = checker.getAliasedSymbol(symbol);
  }
  return checker.getDeclaredTypeOfSymbol(symbol);
}

/** The property names of a type, or of one of its properties (`components` → `schemas`). */
function propertyNames(program: ts.Program, type: ts.Type, property?: string): string[] {
  const checker = program.getTypeChecker();
  if (property === undefined) {
    return checker.getPropertiesOfType(type).map((symbol) => symbol.name);
  }
  const symbol = type.getProperty(property);
  if (symbol === undefined) {
    throw new Error(`the type has no property ${property}`);
  }
  return checker.getPropertiesOfType(checker.getTypeOfSymbol(symbol)).map((member) => member.name);
}

