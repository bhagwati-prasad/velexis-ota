#!/usr/bin/env node
// generate.mjs: generates the contract types of @velexis/api-types from the OpenAPI documents (ADR-0006
// "Workflow" step 3, task X-008).
//
// Usage (from packages/api-types; `pnpm contracts:generate` at the repository root runs it through Turborepo):
//   node scripts/generate.mjs                                  # the documents of ../redocly.yaml into src/generated
//   node scripts/generate.mjs --config <file> --out <dir>      # another copy of the repository layout (tests)
//
// The document locations come from the `apis` of the Redocly config (`ota` and `platform`), the same file that
// `contracts:lint` reads, so the two commands always see the same documents. It writes:
//   - src/generated/ota.ts         openapi-typescript (Node API) on the OTA document;
//   - src/generated/platform.ts    the same on the platform document, or a placeholder with empty `paths`,
//                                  `components` and `operations` until the platform plan creates it in M1;
//   - src/generated/operations.ts  the operations index of both documents, parsed with `yaml`.
// The output is deterministic: no timestamps, no absolute paths, operations in document order. Generated files
// are committed and CI fails when a second run changes them, so never edit them by hand: change the document.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import openapiTS, { astToString } from "openapi-typescript";
import { parse } from "yaml";

const PACKAGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const USAGE = "usage: node scripts/generate.mjs [--config <redocly.yaml>] [--out <dir>]";

/** First line of every generated file. The tests look for it. */
const GENERATED_HEADER = "// Generated by scripts/generate.mjs — do not edit";

/** The HTTP methods of an OpenAPI path item, in the order openapi-typescript and the index use. */
const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

/** Why the platform document may be missing (ADR-0006: the platform plan writes it in M1, PBE-005). */
const PLATFORM_PENDING = "the platform plan creates it in M1 (ADR-0006)";

class GenerateError extends Error {}

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
const message = (err) => (err instanceof Error ? err.message : String(err));
/** A path relative to the repository root with forward slashes, so the output is the same on every machine. */
const repoPath = (root, file) => path.relative(root, file).split(path.sep).join("/");

function readOptions(argv) {
  try {
    const { values } = parseArgs({
      args: argv,
      options: { config: { type: "string" }, out: { type: "string" } },
      strict: true,
    });
    return {
      config: path.resolve(values.config ?? path.join(PACKAGE_DIR, "redocly.yaml")),
      out: path.resolve(values.out ?? path.join(PACKAGE_DIR, "src", "generated")),
    };
  } catch (err) {
    throw new GenerateError(`${message(err)}\n${USAGE}`);
  }
}

/**
 * The `ota` and `platform` documents of the Redocly config, resolved against the config's folder as Redocly does.
 * The config sits at `<root>/packages/api-types/redocly.yaml`, so the repository root is two folders up.
 */
function readDocuments(configFile) {
  let config;
  try {
    config = parse(readFileSync(configFile, "utf8"));
  } catch (err) {
    throw new GenerateError(`cannot read ${configFile}: ${message(err)}`);
  }
  const apis = isObject(config) ? config.apis : undefined;
  const root = path.resolve(path.dirname(configFile), "..", "..");
  const documentOf = (name) => {
    const api = isObject(apis) ? apis[name] : undefined;
    if (!isObject(api) || typeof api.root !== "string" || api.root.trim() === "") {
      throw new GenerateError(`${configFile} has no "apis.${name}.root" document`);
    }
    return path.resolve(path.dirname(configFile), api.root);
  };
  return { root, ota: documentOf("ota"), platform: documentOf("platform") };
}

function parseDocument(file, label) {
  let document;
  try {
    document = parse(readFileSync(file, "utf8"));
  } catch (err) {
    throw new GenerateError(`cannot parse the ${label} document ${file}: ${message(err)}`);
  }
  if (!isObject(document) || typeof document.openapi !== "string" || !isObject(document.paths)) {
    throw new GenerateError(`the ${label} document ${file} is not an OpenAPI 3 document with "paths"`);
  }
  return document;
}

/** An optional vendor extension that must be a non-empty string when present; `null` when absent. */
function optionalString(operation, key, where) {
  const value = operation[key];
  if (value === undefined) {
    return null;
  }
  if (typeof value !== "string" || value.trim() === "") {
    throw new GenerateError(`${where}: "${key}" must be a non-empty string`);
  }
  return value;
}

/**
 * An optional boolean vendor extension; `false` when absent. Only a missing key means `false`: a key without a value
 * (YAML null) is refused, so an `x-internal:` or `x-edge-only:` left empty never reads as "not internal".
 */
function optionalBoolean(operation, key, where) {
  const value = operation[key] === undefined ? false : operation[key];
  if (typeof value !== "boolean") {
    throw new GenerateError(`${where}: "${key}" must be true or false`);
  }
  return value;
}

/**
 * The values of `x-milestone` (ota/docs/api-changes.md §1): the shared milestones M0–M6 of the MVP, or `deferred`
 * for an operation the MVP does not build (its route answers `501 NOT_IMPLEMENTED`).
 */
const MILESTONES = ["M0", "M1", "M2", "M3", "M4", "M5", "M6", "deferred"];

/**
 * The fields of an index entry, in output order: the property name, its TypeScript type in `ApiOperation`, its
 * JSDoc, and how it is read from an operation (`{ operation, method, path, where }`). The `ApiOperation`
 * interface and every entry are written from this table, so a new field is one row here.
 */
const INDEX_FIELDS = [
  {
    name: "operationId",
    type: "TId",
    doc: "The `operationId`, unique in its document.",
    read: ({ operation }) => operation.operationId,
  },
  {
    name: "method",
    type: "HttpMethod",
    doc: "The method, lower case as in `paths[path][method]` of the generated types.",
    read: ({ method }) => method,
  },
  {
    name: "path",
    type: "string",
    doc: "The path template of the document, for example `/v1/bookings/{bookingId}`.",
    read: ({ path: route }) => route,
  },
  {
    name: "sdkMethod",
    type: "string | null",
    doc: "`x-sdk-method`: the dotted SDK method (`bookings.get`), or `null` when the operation has none.",
    read: ({ operation, where }) => optionalString(operation, "x-sdk-method", where),
  },
  {
    name: "scope",
    type: "string | null",
    doc: "`x-scope`: who may call it (OTA `customer`, `console`, `both`; platform `portal`, `platform_admin`, …).",
    read: ({ operation, where }) => optionalString(operation, "x-scope", where),
  },
  {
    name: "tags",
    type: "readonly string[]",
    doc: "The operation's tags, in document order.",
    read: ({ operation, where }) => {
      // Only a missing key means "none": `tags:` without a value (YAML null) is refused, not read as [].
      const tags = operation.tags === undefined ? [] : operation.tags;
      if (!Array.isArray(tags) || !tags.every((tag) => typeof tag === "string")) {
        throw new GenerateError(`${where}: "tags" must be a list of strings`);
      }
      return tags;
    },
  },
  {
    name: "internal",
    type: "boolean",
    doc: "`x-internal: true`: webhook receivers and internal endpoints, never part of the SDK (ADR-0006).",
    read: ({ operation, where }) => optionalBoolean(operation, "x-internal", where),
  },
  {
    name: "milestone",
    type: `${MILESTONES.map((value) => JSON.stringify(value)).join(" | ")} | null`,
    doc:
      "`x-milestone`: the MVP milestone that implements it, or `deferred` (route-parity allow-list, `501`); " +
      "`null` when the operation has none.",
    read: ({ operation, where }) => {
      const milestone = optionalString(operation, "x-milestone", where);
      if (milestone !== null && !MILESTONES.includes(milestone)) {
        throw new GenerateError(`${where}: "x-milestone" must be one of ${MILESTONES.join(", ")}`);
      }
      return milestone;
    },
  },
  {
    name: "edgeOnly",
    type: "boolean",
    doc: "`x-edge-only: true`: only the hosted storefront edge may call it; keys get `403 SCOPE_NOT_ALLOWED`.",
    read: ({ operation, where }) => optionalBoolean(operation, "x-edge-only", where),
  },
  {
    name: "permission",
    type: "string | null",
    doc: "`x-permission`: the `StaffPermission` a console operation needs, or `null` when the operation has none.",
    read: ({ operation, where }) => optionalString(operation, "x-permission", where),
  },
];

/**
 * The operations index of one document: one entry per operation, paths in document order and methods in the
 * fixed order of HTTP_METHODS. Fails on what the parity tests could not key on: a missing or repeated
 * `operationId`, a path item `$ref`, or an extension of the wrong type.
 */
function indexOperations(document, label) {
  const entries = [];
  const seen = new Map();
  for (const [route, item] of Object.entries(document.paths)) {
    if (!isObject(item)) {
      throw new GenerateError(`${label} ${route}: the path item is not an object`);
    }
    if ("$ref" in item) {
      throw new GenerateError(`${label} ${route}: path item "$ref" is not supported by the operations index`);
    }
    for (const method of HTTP_METHODS) {
      const operation = item[method];
      if (operation === undefined) {
        continue;
      }
      const where = `${label} ${method.toUpperCase()} ${route}`;
      if (!isObject(operation)) {
        throw new GenerateError(`${where}: the operation is not an object`);
      }
      const { operationId } = operation;
      if (typeof operationId !== "string" || operationId.trim() === "") {
        throw new GenerateError(`${where}: every operation needs an "operationId"`);
      }
      if (seen.has(operationId)) {
        throw new GenerateError(
          `${where}: "operationId" ${operationId} is also used by ${seen.get(operationId)}`,
        );
      }
      seen.set(operationId, where);
      const context = { operation, method, path: route, where };
      entries.push(Object.fromEntries(INDEX_FIELDS.map((field) => [field.name, field.read(context)])));
    }
  }
  return entries;
}

/** The types of one document, as openapi-typescript writes them, after the repository header. */
async function generateTypes(file, root) {
  let ast;
  try {
    ast = await openapiTS(pathToFileURL(file), { silent: false });
  } catch (err) {
    throw new GenerateError(`openapi-typescript failed on ${repoPath(root, file)}: ${message(err)}`);
  }
  return [
    GENERATED_HEADER,
    `// Source: ${repoPath(root, file)} (openapi-typescript)`,
    "",
    astToString(ast),
  ].join("\n");
}

/** The platform types until the platform document exists: the same exports, all empty. */
function platformPlaceholder(file, root) {
  return [
    GENERATED_HEADER,
    `// Source: ${repoPath(root, file)}, which does not exist yet: ${PLATFORM_PENDING}.`,
    "// Until then this placeholder exports the names openapi-typescript writes, all empty. Once the document",
    "// exists, `pnpm contracts:generate` replaces this file with its types; nothing else changes.",
    "",
    "export interface paths {}",
    "export type webhooks = Record<string, never>;",
    "export interface components {}",
    "export type $defs = Record<string, never>;",
    "export interface operations {}",
    "",
  ].join("\n");
}

function operationLine(entry) {
  const fields = INDEX_FIELDS.map((field) => `${field.name}: ${JSON.stringify(entry[field.name])}`);
  return `  { ${fields.join(", ")} },`;
}

function operationsList(entries) {
  return entries.length === 0 ? "[]" : ["[", ...entries.map(operationLine), "]"].join("\n");
}

function operationsIndex({ root, ota, platform }) {
  const platformSource = platform.entries
    ? `${repoPath(root, platform.file)} (${platform.entries.length} operations)`
    : `${repoPath(root, platform.file)}, which does not exist yet: ${PLATFORM_PENDING}`;
  return [
    GENERATED_HEADER,
    `// Sources: ${repoPath(root, ota.file)} (${ota.entries.length} operations)`,
    `//          ${platformSource}`,
    "// The operations index: one entry per operation, paths in document order. Route-parity and SDK-parity tests",
    "// read it through @velexis/api-types/operations.",
    "",
    'import type { operations as OtaOperations } from "./ota.js";',
    'import type { operations as PlatformOperations } from "./platform.js";',
    "",
    "/** The HTTP methods of an OpenAPI path item, lower case as in the documents and in `paths`. */",
    `export type HttpMethod = ${HTTP_METHODS.map((method) => JSON.stringify(method)).join(" | ")};`,
    "",
    "/** Every `operationId` of the OTA document: the keys of `operations` in `@velexis/api-types`. */",
    "export type OtaOperationId = Extract<keyof OtaOperations, string>;",
    "",
    "/** Every `operationId` of the platform document; `never` while the document does not exist. */",
    "export type PlatformOperationId = Extract<keyof PlatformOperations, string>;",
    "",
    "/** One operation of a document, as the index lists it. */",
    "export interface ApiOperation<TId extends string = string> {",
    ...INDEX_FIELDS.flatMap((field) => [`  /** ${field.doc} */`, `  readonly ${field.name}: ${field.type};`]),
    "}",
    "",
    "/** Freezes the entries, their list values and the list itself. */",
    "function freeze<TId extends string>(entries: ApiOperation<TId>[]): readonly ApiOperation<TId>[] {",
    "  for (const entry of entries) {",
    "    for (const value of Object.values(entry)) {",
    "      if (Array.isArray(value)) {",
    "        Object.freeze(value);",
    "      }",
    "    }",
    "    Object.freeze(entry);",
    "  }",
    "  return Object.freeze(entries);",
    "}",
    "",
    "/** The operations of the OTA booking API (`@velexis/api-types`). */",
    `export const otaOperations = freeze<OtaOperationId>(${operationsList(ota.entries)});`,
    "",
    "/** The operations of the platform API (`@velexis/api-types/platform`); empty until the document exists. */",
    `export const platformOperations = freeze<PlatformOperationId>(${operationsList(platform.entries ?? [])});`,
    "",
  ].join("\n");
}

/** Writes a file only when its content changes, and says which files changed. */
function writeOutput(out, name, content) {
  const file = path.join(out, name);
  const text = content.endsWith("\n") ? content : `${content}\n`;
  const unchanged = existsSync(file) && readFileSync(file, "utf8") === text;
  if (!unchanged) {
    writeFileSync(file, text);
  }
  console.log(`contracts:generate: ${unchanged ? "unchanged" : "wrote"} ${name}`);
}

async function main(argv) {
  const { config, out } = readOptions(argv);
  const { root, ota, platform } = readDocuments(config);
  if (!existsSync(ota)) {
    throw new GenerateError(`the OTA document ${repoPath(root, ota)} does not exist`);
  }
  const platformExists = existsSync(platform);
  if (!platformExists) {
    console.log(
      `contracts:generate: "platform": ${repoPath(root, platform)} does not exist yet; ${PLATFORM_PENDING}. ` +
        "Writing the empty placeholder.",
    );
  }

  const otaEntries = indexOperations(parseDocument(ota, "ota"), "ota");
  const platformEntries = platformExists
    ? indexOperations(parseDocument(platform, "platform"), "platform")
    : null;
  const otaTypes = await generateTypes(ota, root);
  const platformTypes = platformExists
    ? await generateTypes(platform, root)
    : platformPlaceholder(platform, root);
  const index = operationsIndex({
    root,
    ota: { file: ota, entries: otaEntries },
    platform: { file: platform, entries: platformEntries },
  });

  mkdirSync(out, { recursive: true });
  writeOutput(out, "ota.ts", otaTypes);
  writeOutput(out, "platform.ts", platformTypes);
  writeOutput(out, "operations.ts", index);
  console.log(
    `contracts:generate: ${otaEntries.length} OTA and ${platformEntries?.length ?? 0} platform operations indexed.`,
  );
}

try {
  await main(process.argv.slice(2));
} catch (err) {
  if (!(err instanceof GenerateError)) {
    throw err;
  }
  console.error(`contracts:generate: ${err.message}`);
  process.exitCode = 1;
}
