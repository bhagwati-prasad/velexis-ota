import { createHmac, timingSafeEqual } from "node:crypto";

/**
 * Short-lived signed download URLs for booking documents (ADR-0017, Signed URLs): the OTA backend serves
 * `GET /v1/files/<storageKey>?exp=<unix>&sig=<sig>` with
 * `sig = base64url(HMAC-SHA-256(key, "<path>?exp=<unix>"))` and `key` the decoded `document-url.key`.
 *
 * Only the path and the expiry are signed, not the host: the same link works same-origin under `/api` on
 * the hosted storefront (Caddy strips the prefix) and on the API host.
 */

/** Minimum key length in bytes: `document-url.key` holds 32 random bytes (ADR-0010). */
export const SIGNED_URL_KEY_MIN_BYTES = 32;

/**
 * A signable path: `/`-separated segments of URL-unreserved characters (`A-Z a-z 0-9 - . _ ~`), none of
 * them empty, `.` or `..`. Such a path needs no percent-encoding, so the signed string and the string a
 * server receives are the same, and no dot segment can be normalised away in between.
 */
const SEGMENT = /^[A-Za-z0-9._~-]+$/;
const MAX_PATH_LENGTH = 2048;
/** The query a signed URL carries, in this order and nothing else; `exp` has no leading zeros. */
const SIGNED_QUERY = /^exp=([1-9][0-9]{0,11})&sig=([A-Za-z0-9_-]{43})$/;
/** Scheme and authority of an absolute URL, which is not part of the signature. */
const ORIGIN = /^https?:\/\/[^/?#]+/i;

export interface SignUrlOptions {
  /** End of validity. It is rounded down to whole seconds (`exp` is a Unix time in seconds). */
  readonly expiresAt: Date;
  /** The HMAC key: the decoded `document-url.key`, at least 32 bytes. */
  readonly key: Uint8Array;
}

export interface VerifySignedUrlOptions {
  readonly key: Uint8Array;
  /** The current time, from the injected clock. The link is valid up to and including `exp`. */
  readonly now: Date;
}

export type SignedUrlVerification =
  | {
      readonly valid: true;
      /** The signed path, for example `/v1/files/tenant_acme/…/itinerary-v1.pdf`. */
      readonly path: string;
      readonly expiresAt: Date;
    }
  | {
      readonly valid: false;
      /** Why the link was refused; for logs and metrics only. Every reason answers the same `403`. */
      readonly reason: "malformed" | "signature" | "expired";
    };

function isSignablePath(path: unknown): path is string {
  if (typeof path !== "string" || path.length > MAX_PATH_LENGTH || !path.startsWith("/")) {
    return false;
  }
  return path
    .slice(1)
    .split("/")
    .every((segment) => SEGMENT.test(segment) && segment !== "." && segment !== "..");
}

function assertKey(key: unknown, fn: string): asserts key is Uint8Array {
  if (!(key instanceof Uint8Array) || key.length < SIGNED_URL_KEY_MIN_BYTES) {
    throw new TypeError(
      `${fn}(): key must be a Buffer of at least ${SIGNED_URL_KEY_MIN_BYTES} bytes (the decoded document-url.key)`,
    );
  }
}

function signature(key: Uint8Array, path: string, exp: string): string {
  return createHmac("sha256", key).update(`${path}?exp=${exp}`, "utf8").digest("base64url");
}

/**
 * Signs `path` until `expiresAt` and returns `"<path>?exp=<unix>&sig=<sig>"`. Prefix it with the API
 * origin, or with `/api` for the hosted storefront. The path must be signable (see `SEGMENT`); storage
 * keys are generated by the application and always are.
 */
export function signUrl(path: string, options: SignUrlOptions): string {
  if (!isSignablePath(path)) {
    throw new TypeError(
      "signUrl(): path must start with / and have only non-empty segments of A-Z a-z 0-9 - . _ ~ (no . or ..)",
    );
  }
  assertKey(options.key, "signUrl");
  const { expiresAt } = options;
  const expMs = expiresAt instanceof Date ? expiresAt.getTime() : Number.NaN;
  const exp = Math.floor(expMs / 1000);
  if (!Number.isSafeInteger(exp) || exp < 1 || exp > 999_999_999_999) {
    throw new TypeError("signUrl(): expiresAt must be a valid Date after 1970-01-01T00:00:01Z");
  }
  const expText = String(exp);
  return `${path}?exp=${expText}&sig=${signature(options.key, path, expText)}`;
}

/**
 * Checks a URL made by `signUrl`: a path with its query (`req.originalUrl`) or an absolute URL, whose
 * host is ignored. The query must be exactly `exp=<unix>&sig=<sig>`. The signature is compared in
 * constant time, and the link is refused once `now` is after `exp`.
 */
export function verifySignedUrl(url: string, options: VerifySignedUrlOptions): SignedUrlVerification {
  assertKey(options.key, "verifySignedUrl");
  const { now } = options;
  if (!(now instanceof Date) || Number.isNaN(now.getTime())) {
    throw new TypeError("verifySignedUrl(): now must be a valid Date");
  }
  if (typeof url !== "string") {
    return { valid: false, reason: "malformed" };
  }

  const relative = url.replace(ORIGIN, "");
  const queryStart = relative.indexOf("?");
  const path = queryStart === -1 ? relative : relative.slice(0, queryStart);
  const query = SIGNED_QUERY.exec(queryStart === -1 ? "" : relative.slice(queryStart + 1));
  const expText = query?.[1];
  const sig = query?.[2];
  if (expText === undefined || sig === undefined || !isSignablePath(path)) {
    return { valid: false, reason: "malformed" };
  }

  const expected = Buffer.from(signature(options.key, path, expText), "ascii");
  if (!timingSafeEqual(expected, Buffer.from(sig, "ascii"))) {
    return { valid: false, reason: "signature" };
  }
  const expiresAt = new Date(Number(expText) * 1000);
  if (now.getTime() > expiresAt.getTime()) {
    return { valid: false, reason: "expired" };
  }
  return { valid: true, path, expiresAt };
}
