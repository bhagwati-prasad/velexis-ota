test("serve.mjs serves the guidebook and refuses path traversal", async () => {
  const server = createServer(path.resolve(TOOLS, ".."));
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  const { port } = server.address();
  const get = (p) => fetch(`http://127.0.0.1:${port}${p}`);
  try {
    const index = await get("/");
    assert.equal(index.status, 200);
    assert.match(index.headers.get("content-type"), /text\/html/);
    assert.match(await index.text(), /<title>Velexis Guidebook<\/title>/);
    const css = await get("/assets/css/guide.css");
    assert.equal(css.status, 200);
    assert.match(css.headers.get("content-type"), /text\/css/);
    assert.equal((await get("/nope.js")).status, 404);
    assert.notEqual((await get("/%2e%2e/%2e%2e/etc/passwd")).status, 200);
    assert.equal((await fetch(`http://127.0.0.1:${port}/`, { method: "POST" })).status, 405);
  } finally {
    await new Promise((resolve) => server.close(resolve));
  }
});
