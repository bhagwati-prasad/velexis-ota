test("fixture bundle has every diagram type, the graph, the search index and backlinks", () => {
  const { data, stats } = build({ contentDir: FIXTURES, repoRoot: null });
  for (const type of DIAGRAM_TYPES)
    assert.ok(stats.diagramsByType[type] >= 1, `missing diagram type ${type}`);
  assert.ok(stats.terms >= 25);
  assert.ok(stats.journeys >= 2 && stats.pages >= 2 && stats.flows >= 2);
  // graph: every edge points at a node; nodes and edges are sorted
  const ids = new Set(data.graph.nodes.map((n) => n.id));
  for (const e of data.graph.edges)
    assert.ok(ids.has(e.source) && ids.has(e.target), `${e.source} -> ${e.target}`);
  const sortedIds = [...data.graph.nodes.map((n) => n.id)].sort((x, y) => (x < y ? -1 : x > y ? 1 : 0));
  assert.deepEqual(
    data.graph.nodes.map((n) => n.id),
    sortedIds,
  );
  for (const kind of ["app", "term", "class", "individual", "page", "journey", "issue"]) {
    assert.ok(
      data.graph.nodes.some((n) => n.kind === kind),
      `no ${kind} node`,
    );
  }
  assert.ok(data.graph.edges.some((e) => e.label === "subclass of"));
  assert.ok(data.graph.edges.some((e) => e.label === "depends on"));
  // search index covers every kind the brief names
  for (const k of [
    "page",
    "section",
    "term",
    "app",
    "screen",
    "endpoint",
    "journey",
    "diagram",
    "class",
    "issue",
  ]) {
    assert.ok(
      data.search.some((s) => s.k === k),
      `no ${k} in the search index`,
    );
  }
  // backlinks: the overview page mentions [[tenant]]
  const tenant = data.terms.find((t) => t.id === "tenant");
  assert.ok(tenant.backlinks.some((b) => b.kind === "page" && b.id === "overview"));
  // diagrams know where they are used
  assert.ok(data.diagrams["portal/neighbours"].usedIn.length >= 2);
  // heading slugs are unique per document
  for (const p of data.pages) {
    const slugs = p.headings.map((x) => x.slug);
    assert.equal(new Set(slugs).size, slugs.length, `duplicate slug in ${p.id}`);
  }
});

test("fixture issues: bundle, aliases, stats, search entries, graph nodes and backlinks", () => {
  const { data, stats } = build({ contentDir: FIXTURES, repoRoot: null });
  assert.deepEqual(
    data.issues.map((x) => x.id),
    ["KI-001", "KI-002", "KI-003"],
  );
  // the app alias of site.json ("backend") resolves to the app id
  assert.equal(data.issues.find((x) => x.id === "KI-002").app, "platform-api");
  for (const x of data.issues) {
    assert.ok(ISSUE_SEVERITIES.includes(x.severity) && ISSUE_KINDS.includes(x.kind));
    assert.ok(ISSUE_STATUSES.includes(x.status));
  }
  assert.equal(stats.issues, 3);
  assert.deepEqual(stats.issuesBySeverity, { high: 1, low: 1, medium: 1 });
  assert.deepEqual(stats.issuesByStatus, { confirmed: 2, plausible: 1 });
  assert.deepEqual(stats.issuesByApp, { "platform-api": 2, portal: 1 });
  assert.equal(data.stats.issuesByKind.db, 1);
  // search: one entry per issue, opening its page
  const entry = data.search.find((e) => e.k === "issue" && e.id === "KI-001");
  assert.ok(entry, "no search entry for KI-001");
  assert.equal(entry.r, "#/issue/KI-001");
  assert.equal(entry.a, "portal");
  assert.match(entry.x, /ki-001 high ux confirmed/);
  assert.equal(data.search.filter((e) => e.k === "issue").length, 3);
  // graph: an issue node linked to its app, journey and terms
  const node = data.graph.nodes.find((n) => n.id === "issue:KI-001");
  assert.equal(node.kind, "issue");
  assert.equal(node.category, "high");
  assert.equal(node.route, "#/issue/KI-001");
  const edges = data.graph.edges.filter((e) => e.source === "issue:KI-001");
  assert.ok(edges.some((e) => e.target === "app:portal" && e.label === "affects"));
  assert.ok(edges.some((e) => e.target === "journey:sign-up-and-create-ota" && e.label === "seen in"));
  assert.ok(edges.some((e) => e.target === "term:bff" && e.label === "about"));
  // backlinks: the terms field and a [[term]] in the summary both count
  const bff = data.terms.find((t) => t.id === "bff");
  assert.ok(
    bff.backlinks.some((b) => b.kind === "issue" && b.id === "KI-001" && b.route === "#/issue/KI-001"),
  );
  const tenant = data.terms.find((t) => t.id === "tenant");
  assert.equal(tenant.backlinks.filter((b) => b.kind === "issue" && b.id === "KI-001").length, 1);
});

