const TOOLS = path.dirname(fileURLToPath(import.meta.url));
const FIXTURES = path.join(TOOLS, "fixtures", "content");
const BUILD = path.join(TOOLS, "build.mjs");
const TMP_PREFIX = path.join(os.tmpdir(), "vg-guidebook-test-");

function tmpDir() {
  return fs.mkdtempSync(TMP_PREFIX);
}
function cleanup(dir) {
  // only ever removes a folder this file created with mkdtemp
  if (dir && dir.startsWith(TMP_PREFIX)) fs.rmSync(dir, { recursive: true, force: true });
}
function copyFixtures() {
  const dir = tmpDir();
  fs.cpSync(FIXTURES, dir, { recursive: true });
  return dir;
}
function editJson(file, fn) {
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const out = fn(data);
  fs.writeFileSync(file, JSON.stringify(out === undefined ? data : out, null, 2));
}
function editText(file, fn) {
  fs.writeFileSync(file, fn(fs.readFileSync(file, "utf8")));
}
function cli(args) {
  const r = spawnSync(process.execPath, [BUILD, ...args], { encoding: "utf8" });
  return { code: r.status, out: r.stdout + r.stderr };
}
/** Builds a broken copy of the fixtures and returns its errors. */
function brokenErrors(mutate, opts = {}) {
  const dir = copyFixtures();
  try {
    mutate(dir);
    return build({ contentDir: dir, repoRoot: opts.repoRoot === undefined ? null : opts.repoRoot }).errors;
  } finally {
    cleanup(dir);
  }
}
const hasError = (errors, re) => errors.some((e) => re.test(e));

