function realContentPresent() {
  const apps = path.join(DEFAULT_CONTENT, "apps");
  return (
    fs.existsSync(apps) && fs.readdirSync(apps).some((d) => fs.existsSync(path.join(apps, d, "app.json")))
  );
}

// Inside the repository the content and dist/content.js are committed sources and CI runs this suite (lead decision
// (35e)): there an empty content folder or a missing bundle fails, so CI never passes with a skip instead.
const IN_REPOSITORY = findRepoRoot() !== null;

test("the real content builds without errors", (t) => {
  if (!realContentPresent()) {
    assert.ok(
      !IN_REPOSITORY,
      "guidebook/content/apps has no app, but the guidebook is inside the repository",
    );
    return t.skip("guidebook/content/apps is still empty: nothing to build yet");
  }
  const r = build({ contentDir: DEFAULT_CONTENT });
  // a short message: the first errors and a count (run node guidebook/tools/build.mjs for the full list)
  assert.ok(
    r.errors.length === 0,
    `${r.errors.length} errors in guidebook/content, first ones:\n${r.errors.slice(0, 15).join("\n")}`,
  );
});

test("dist/content.js is up to date with the real content", (t) => {
  if (!realContentPresent()) {
    assert.ok(
      !IN_REPOSITORY,
      "guidebook/content/apps has no app, but the guidebook is inside the repository",
    );
    return t.skip("guidebook/content/apps is still empty: nothing to compare");
  }
  if (!fs.existsSync(DEFAULT_OUT)) {
    assert.ok(!IN_REPOSITORY, "dist/content.js is missing: run node guidebook/tools/build.mjs and commit it");
    return t.skip("dist/content.js has not been built yet (run node guidebook/tools/build.mjs)");
  }
  const r = build({ contentDir: DEFAULT_CONTENT });
  assert.equal(
    fs.readFileSync(DEFAULT_OUT, "utf8"),
    r.output,
    "dist/content.js is stale: run node guidebook/tools/build.mjs",
  );
});

