test("fixture content builds without errors", () => {
  const r = build({ contentDir: FIXTURES, repoRoot: null });
  assert.deepEqual(r.errors, []);
  // without a repository root only the "repo paths not checked" warning is allowed
  assert.ok(
    r.warnings.every((w) => /repository root not found/.test(w)),
    r.warnings.join("\n"),
  );
  // the first line is the Prettier guard, then the generated-file notice, then the one statement
  assert.ok(r.output.startsWith("// prettier-ignore\n/* Generated by guidebook/tools/build.mjs"));
  assert.match(r.output, /^\/\/ prettier-ignore\n\/\* Generated [^\n]*\*\/\nwindow\.VG_CONTENT = \{/);
});

