/*
 * Velexis Guidebook tests (node:test, zero dependencies):  node --test guidebook/tools/guidebook.test.mjs
 *
 * - the fixture content builds without errors, deterministically, with every diagram type and the known issues;
 * - every validation error kind is detected on small broken copies of the fixtures;
 * - --check detects a stale or missing dist; --strict fails on warnings; empty content still builds;
 * - the real content builds and dist/content.js is up to date (outside the repository skipped with a message while
 *   content is empty or the bundle is not built; inside it neither is a reason to skip);
 * - the static server serves the folder and refuses path traversal.
 */
