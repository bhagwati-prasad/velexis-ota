test("the bundle does not depend on whether the repository root was found", () => {
  // a scratch copy (no repository) and a checkout inside the repository must write the same dist/content.js
  const dir = tmpDir();
  try {
    const without = build({ contentDir: FIXTURES, repoRoot: null });
    const withRoot = build({ contentDir: FIXTURES, repoRoot: dir });
    assert.equal(without.stats.repoPathsChecked, 0);
    assert.ok(withRoot.stats.repoPathsChecked > 0);
    assert.equal(withRoot.output, without.output);
    assert.equal(without.data.stats.repoPathsChecked, undefined);
    assert.ok(without.data.stats.repoPaths > 0);
  } finally {
    cleanup(dir);
  }
});

