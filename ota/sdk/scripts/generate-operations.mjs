#!/usr/bin/env node
// generate-operations.mjs: generates the SDK route table src/internal/operations.js from the working
// OpenAPI document of the OTA booking API (OADR-0016 point 2, ota/sdk/docs/types-and-builds.md §5, SDK-002), and
// the per-method assertions of the contract test, test/contract/methods.generated.ts (OADR-0016 point 4,
// ota/sdk/docs/types-and-builds.md §4, SDK-006).
//
// Usage (from ota/sdk; `pnpm --filter @velexis/ota-sdk generate` runs it, and `pnpm contracts:generate` runs
// every package's `generate` through Turborepo):
//   node scripts/generate-operations.mjs
//   node scripts/generate-operations.mjs --document <yaml> --overrides <json> --out <file>   # tests
//   node scripts/generate-operations.mjs --document <yaml> --out <file> \
//     --contract-document <yaml> --methods-out <file>                                        # tests
//
// A run without `--out` writes both files to their committed places. A run with `--out` (a test of the route
// table) writes the assertions only to an explicit `--methods-out`, so it never overwrites the committed file.
//
// One frozen entry per `x-sdk-method`, keyed by the method with its dots replaced by underscores
// (`console.bookings.issue` -> `console_bookings_issue`). Each entry says how `core.call` turns the params of a
// call into an HTTP request: the method and path template, which params fill the path, the query and the
// headers, whether the operation takes an `Idempotency-Key`, how it may be retried and its reviewed timeout.
// Operations marked `x-internal` or `x-sdk-exclude` have no SDK method and are skipped. Values the document
// does not carry (timeouts above the client default, `retry: "never"`) come from
// scripts/operation-overrides.json, reviewed like code.
//
// The generator fails (exit 1, nothing written) on what core.call could only guess at: a duplicated
// `x-sdk-method`, a public operation without one, a param name used twice in one operation (path, query,
// header or top-level body property), a header or a query serialisation the SDK does not know, a path
// template that does not match its path params, or an override for a method that is not in the document.
// The output is deterministic (entries sorted by key, no timestamps, no absolute paths), committed, and CI
// fails when a second run changes it: never edit it by hand, change the document or the overrides.
//
// The assertions file has one type per `x-sdk-method` of the route table. A method of the frozen contract (an
// `x-sdk-method` of docs/velexis-sdk/openapi/, the document the TypeScript contract in docs/velexis-sdk/sdk/src/
// was written for) gets `Conforms`: the contract's parameters are assignable to the SDK's and the SDK's awaited
// result to the contract's. Any other method is an addition (ota/sdk/docs/extensions.md) and gets `Addition`: the
// client has it and the contract does not. The helpers, the pending list and the approved deviations are in
// test/contract/; the file is formatted the way Prettier formats it, so `pnpm format:check` passes unchanged.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parse } from "yaml";

const SDK_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = path.resolve(SDK_DIR, "..", "..");
const DEFAULTS = {
  document: path.join(REPO_ROOT, "ota", "backend", "openapi", "velexis-ota-booking-api.openapi.yaml"),
  overrides: path.join(SDK_DIR, "scripts", "operation-overrides.json"),
  out: path.join(SDK_DIR, "src", "internal", "operations.js"),
  /** The frozen original design, never edited (decisions.md §3): its `x-sdk-method`s are the contract's methods. */
  contractDocument: path.join(
    REPO_ROOT,
    "docs",
    "velexis-sdk",
    "openapi",
    "velexis-ota-booking-api.openapi.yaml",
  ),
  methods: path.join(SDK_DIR, "test", "contract", "methods.generated.ts"),
};
const USAGE =
  "usage: node scripts/generate-operations.mjs [--document <openapi.yaml>] [--overrides <json>] [--out <file>]" +
  " [--contract-document <openapi.yaml>] [--methods-out <file>]";

/** First line of the generated file. The tests look for it. */
const GENERATED_HEADER = "// Generated by scripts/generate-operations.mjs — do not edit.";

/** The HTTP methods of an OpenAPI path item, in the order of the operations index of @velexis/api-types. */
const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];
/** The methods an SDK operation may use. */
const SDK_METHODS = new Set(["get", "put", "post", "delete", "patch"]);
/** Methods that change nothing on the server: retried freely (README §5.3). */
const SAFE_METHODS = new Set(["get"]);
/** Methods that HTTP defines as idempotent: retried like requests that carry an `Idempotency-Key` (README §5.3). */
const IDEMPOTENT_METHODS = new Set(["put", "delete"]);

/** `namespace.method` or `namespace.group.method`, each segment a camelCase identifier (no underscores). */
const SDK_METHOD_PATTERN = /^[a-z][A-Za-z0-9]*(?:\.[a-z][A-Za-z0-9]*)+$/;
/** A task id of the plans, for example `OBE-029`. */
const TASK_ID_PATTERN = /^[A-Z]+-\d{3}$/;

/**
 * Header parameters that a caller passes as a named param of the method, by lower-case header name. `core.call`
 * sends `params.ifMatch` as `If-Match` (README §3, "How a method is written").
 */
const HEADER_PARAMS = new Map([["if-match", { param: "ifMatch", header: "If-Match" }]]);

/**
 * Header parameters that the client sets itself, so they are not method params, by lower-case header name. The
 * value says where each comes from. `Idempotency-Key` (the entry's `idempotency`) and `X-Velexis-Environment` (its
 * `environment`) are read separately. Any other header parameter fails the generator: a new header needs a reviewed
 * decision here, not a silent guess.
 */
const CLIENT_HEADERS = new Map([
  ["accept-language", "the `locale` option of the client or the call"],
  ["x-currency", "the `currency` option of the client or the call"],
  ["x-csrf-token", "cookie mode copies the `__Host-vx_csrf` cookie on writes (internal/session.js)"],
  ["x-velexis-host", "the `host` option of the client or the call (identity.d.ts)"],
  ["x-velexis-end-user-ip", "the `endUser` option of the client or the call (identity.d.ts)"],
  ["x-velexis-end-user-agent", "the `endUser` option of the client or the call (identity.d.ts)"],
  ["x-velexis-scope", "`RequestOptions.headers` of the call (flights.d.ts)"],
  ["if-none-match", "`RequestOptions.headers` of the call, or the fetch cache"],
]);
const IDEMPOTENCY_HEADER = "idempotency-key";
const ENVIRONMENT_HEADER = "x-velexis-environment";

/** Request body media types and the `body` value that tells core.call how to send the remaining params. */
const BODY_TYPES = new Map([
  ["application/json", "json"],
  ["multipart/form-data", "multipart"],
]);

/** Fields an override may set, besides its `reason` and the `specTask` of an operation not in the document yet. */
const OVERRIDE_FIELDS = new Set(["timeoutMs", "retry", "reason", "specTask"]);
/** The longest reviewed timeout: ten minutes. */
const MAX_TIMEOUT_MS = 600_000;

class GenerateError extends Error {}

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
const message = (err) => (err instanceof Error ? err.message : String(err));
/** A path relative to the repository root with forward slashes, so the output is the same on every machine. */
const repoPath = (file) => path.relative(REPO_ROOT, file).split(path.sep).join("/");
/** Code-unit order, the same on every machine (no locale). */
const byCodeUnits = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

function readOptions(argv) {
  try {
    const { values } = parseArgs({
      args: argv,
      options: {
        document: { type: "string" },
        overrides: { type: "string" },
        out: { type: "string" },
        "contract-document": { type: "string" },
        "methods-out": { type: "string" },
      },
      strict: true,
    });
    // With `--out` (a test of the route table), the assertions go only where `--methods-out` says.
    let methods = null;
    if (values["methods-out"] !== undefined) {
      methods = path.resolve(values["methods-out"]);
    } else if (values.out === undefined) {
      methods = DEFAULTS.methods;
    }
    return {
      document: path.resolve(values.document ?? DEFAULTS.document),
      overrides: path.resolve(values.overrides ?? DEFAULTS.overrides),
      out: path.resolve(values.out ?? DEFAULTS.out),
      contractDocument: path.resolve(values["contract-document"] ?? DEFAULTS.contractDocument),
      methods,
    };
  } catch (err) {
    throw new GenerateError(`${message(err)}\n${USAGE}`);
  }
}

function readDocument(file) {
  if (!existsSync(file)) {
    throw new GenerateError(`the OpenAPI document ${file} does not exist`);
  }
  let document;
  try {
    document = parse(readFileSync(file, "utf8"));
  } catch (err) {
    throw new GenerateError(`cannot parse the OpenAPI document ${file}: ${message(err)}`);
  }
  if (!isObject(document) || typeof document.openapi !== "string" || !isObject(document.paths)) {
    throw new GenerateError(`${file} is not an OpenAPI 3 document with "paths"`);
  }
  return document;
}

/** Follows local `$ref`s (`#/components/...`) until a value without one; fails on a cycle or a dangling `$ref`. */
function resolve(document, value, where) {
  let current = value;
  const seen = new Set();
  while (isObject(current) && typeof current.$ref === "string") {
    const ref = current.$ref;
    if (!ref.startsWith("#/") || seen.has(ref)) {
      throw new GenerateError(`${where}: cannot resolve "$ref" ${ref}`);
    }
    seen.add(ref);
    current = ref
      .slice(2)
      .split("/")
      .map((part) => part.replace(/~1/g, "/").replace(/~0/g, "~"))
      .reduce((node, part) => (isObject(node) ? node[part] : undefined), document);
    if (current === undefined) {
      throw new GenerateError(`${where}: "$ref" ${ref} points at nothing`);
    }
  }
  return current;
}

/** An optional boolean vendor extension; `false` when absent. A key without a value (YAML null) is refused. */
function optionalBoolean(operation, key, where) {
  const value = operation[key] === undefined ? false : operation[key];
  if (typeof value !== "boolean") {
    throw new GenerateError(`${where}: "${key}" must be true or false`);
  }
  return value;
}

/** The parameters of an operation: those of its path item, replaced by its own with the same name and location. */
function parametersOf(document, item, operation, where) {
  const merged = new Map();
  for (const list of [item.parameters, operation.parameters]) {
    if (list === undefined) {
      continue;
    }
    if (!Array.isArray(list)) {
      throw new GenerateError(`${where}: "parameters" must be a list`);
    }
    for (const raw of list) {
      const parameter = resolve(document, raw, where);
      if (!isObject(parameter) || typeof parameter.name !== "string" || typeof parameter.in !== "string") {
        throw new GenerateError(`${where}: every parameter needs a "name" and an "in"`);
      }
      const name = parameter.in === "header" ? parameter.name.toLowerCase() : parameter.name;
      merged.set(`${parameter.in}:${name}`, parameter);
    }
  }
  return [...merged.values()];
}

/** The `{name}` placeholders of a path template, in order. */
const templateNames = (route) => [...route.matchAll(/\{([^{}]+)\}/g)].map((match) => match[1]);

/**
 * A query parameter must be sent the way core.call sends every query parameter: one `name=value`, arrays
 * comma-separated (`style: form`, `explode: false`), never an object.
 */
function checkQuerySerialisation(document, parameter, where) {
  const label = `${where}: query parameter "${parameter.name}"`;
  if (parameter.content !== undefined) {
    throw new GenerateError(`${label} uses "content"; the SDK sends query parameters as plain values`);
  }
  if (parameter.style !== undefined && parameter.style !== "form") {
    throw new GenerateError(`${label} has style "${parameter.style}"; the SDK sends only style "form"`);
  }
  const schema = resolve(document, parameter.schema ?? {}, label);
  const types = [schema.type].flat();
  if (types.includes("object")) {
    throw new GenerateError(`${label} is an object; the SDK sends no object query parameters`);
  }
  if (types.includes("array") && parameter.explode !== false) {
    throw new GenerateError(
      `${label} is an array without "explode: false"; the SDK sends arrays comma-separated`,
    );
  }
}

/** The top-level property names of a request body schema, through `allOf`, `oneOf` and `anyOf`. */
function bodyPropertyNames(document, schema, where, seen = new Set()) {
  if (isObject(schema) && typeof schema.$ref === "string") {
    if (seen.has(schema.$ref)) {
      return [];
    }
    seen.add(schema.$ref);
  }
  const resolved = resolve(document, schema, where);
  if (!isObject(resolved)) {
    return [];
  }
  const names = isObject(resolved.properties) ? Object.keys(resolved.properties) : [];
  for (const key of ["allOf", "oneOf", "anyOf"]) {
    if (Array.isArray(resolved[key])) {
      for (const part of resolved[key]) {
        names.push(...bodyPropertyNames(document, part, where, seen));
      }
    }
  }
  return [...new Set(names)];
}

/** How the request body is sent (`json`, `multipart` or `null` for none) and its top-level property names. */
function readBody(document, operation, where) {
  if (operation.requestBody === undefined) {
    return { body: null, names: [] };
  }
  const requestBody = resolve(document, operation.requestBody, where);
  const types =
    isObject(requestBody) && isObject(requestBody.content) ? Object.keys(requestBody.content) : [];
  if (types.length !== 1 || !BODY_TYPES.has(types[0])) {
    throw new GenerateError(
      `${where}: the request body must have exactly one media type of ${[...BODY_TYPES.keys()].join(", ")}` +
        ` (found ${types.length === 0 ? "none" : types.join(", ")})`,
    );
  }
  const names = bodyPropertyNames(document, requestBody.content[types[0]].schema ?? {}, where);
  return { body: BODY_TYPES.get(types[0]), names };
}

/**
 * The route-table entry of one SDK operation, without the reviewed overrides: the retry class is `safe` for GET,
 * `idempotent` for PUT and DELETE, for any request with an `Idempotency-Key` and for a POST or PATCH marked
 * `x-idempotent-by-design`, and `never` otherwise; `timeoutMs` is `null` (the client's `timeoutMs`).
 */
function entryOf(document, { item, operation, method, route, sdkMethod, where }) {
  const pathParams = [];
  const queryParams = [];
  const headerParams = {};
  let idempotency = "none";
  let environment = false;
  /** Every param name of the call and where it goes, to catch two places that want the same name. */
  const owners = new Map();
  const claim = (name, owner) => {
    if (owners.has(name)) {
      throw new GenerateError(
        `${where} (${sdkMethod}): the param name "${name}" is both ${owners.get(name)} and ${owner}; ` +
          "core.call could only guess where it goes. Rename one of them in the document.",
      );
    }
    owners.set(name, owner);
  };

  for (const parameter of parametersOf(document, item, operation, where)) {
    switch (parameter.in) {
      case "path":
        if (parameter.required !== true) {
          throw new GenerateError(`${where}: path parameter "${parameter.name}" must be required`);
        }
        claim(parameter.name, "a path parameter");
        pathParams.push(parameter.name);
        break;
      case "query":
        checkQuerySerialisation(document, parameter, where);
        claim(parameter.name, "a query parameter");
        queryParams.push(parameter.name);
        break;
      case "header": {
        const header = parameter.name.toLowerCase();
        if (header === IDEMPOTENCY_HEADER) {
          idempotency = parameter.required === true ? "required" : "optional";
        } else if (header === ENVIRONMENT_HEADER) {
          environment = true;
        } else if (HEADER_PARAMS.has(header)) {
          const mapped = HEADER_PARAMS.get(header);
          claim(mapped.param, `the header ${mapped.header}`);
          headerParams[mapped.param] = mapped.header;
        } else if (!CLIENT_HEADERS.has(header)) {
          throw new GenerateError(
            `${where}: the header parameter "${parameter.name}" is unknown to the SDK; decide in ` +
              "scripts/generate-operations.mjs whether it is a method param or set by the client",
          );
        }
        break;
      }
      case "cookie":
        // Cookies are the browser's (cookie mode); the SDK never sets one.
        break;
      default:
        throw new GenerateError(
          `${where}: parameter "${parameter.name}" has an unknown "in": ${parameter.in}`,
        );
    }
  }

  const placeholders = templateNames(route);
  // claim() already refused a path param declared twice, so equal sizes, no repeated placeholder and every
  // placeholder declared mean the template and the path params name exactly the same params.
  const matches =
    placeholders.length === pathParams.length &&
    new Set(placeholders).size === placeholders.length &&
    placeholders.every((name) => pathParams.includes(name));
  if (!matches) {
    throw new GenerateError(
      `${where}: the path template names {${placeholders.join("}, {")}} but the path parameters are ` +
        `${pathParams.length === 0 ? "none" : pathParams.join(", ")}`,
    );
  }

  const { body, names } = readBody(document, operation, where);
  for (const name of names) {
    claim(name, "a top-level property of the request body");
  }

  const byDesign = optionalBoolean(operation, "x-idempotent-by-design", where);
  let retry = "never";
  if (SAFE_METHODS.has(method)) {
    retry = "safe";
  } else if (IDEMPOTENT_METHODS.has(method) || idempotency !== "none" || byDesign) {
    retry = "idempotent";
  }

  return {
    method: method.toUpperCase(),
    path: route,
    // In the order of the template, so the table reads like the path.
    pathParams: placeholders,
    queryParams,
    headerParams,
    idempotency,
    retry,
    timeoutMs: null,
    environment,
    body,
  };
}

/** Every SDK operation of the document as `{ key, sdkMethod, entry }`, sorted by key. */
function collectOperations(document) {
  const owners = new Map();
  const operations = [];
  for (const [route, item] of Object.entries(document.paths)) {
    if (!isObject(item)) {
      throw new GenerateError(`${route}: the path item is not an object`);
    }
    if ("$ref" in item) {
      throw new GenerateError(`${route}: path item "$ref" is not supported`);
    }
    for (const method of HTTP_METHODS) {
      const operation = item[method];
      if (operation === undefined) {
        continue;
      }
      const where = `${method.toUpperCase()} ${route}`;
      if (!isObject(operation)) {
        throw new GenerateError(`${where}: the operation is not an object`);
      }
      const sdkMethod = operation["x-sdk-method"];
      const skipped =
        optionalBoolean(operation, "x-internal", where) || optionalBoolean(operation, "x-sdk-exclude", where);
      if (sdkMethod === undefined) {
        if (skipped) {
          continue;
        }
        throw new GenerateError(
          `${where}: every operation needs an "x-sdk-method" unless it is "x-internal" or "x-sdk-exclude"`,
        );
      }
      if (typeof sdkMethod !== "string" || !SDK_METHOD_PATTERN.test(sdkMethod)) {
        throw new GenerateError(
          `${where}: "x-sdk-method" must be dotted camelCase names such as "flights.search" ` +
            `(found ${JSON.stringify(sdkMethod)})`,
        );
      }
      if (owners.has(sdkMethod)) {
        throw new GenerateError(
          `${where}: "x-sdk-method" ${sdkMethod} is also used by ${owners.get(sdkMethod)}; ` +
            "every SDK method maps to exactly one operation",
        );
      }
      owners.set(sdkMethod, where);
      if (skipped) {
        continue;
      }
      if (!SDK_METHODS.has(method)) {
        throw new GenerateError(`${where}: the SDK does not call ${method.toUpperCase()} operations`);
      }
      const entry = entryOf(document, { item, operation, method, route, sdkMethod, where });
      operations.push({ key: sdkMethod.replaceAll(".", "_"), sdkMethod, entry });
    }
  }
  return { operations: operations.sort((a, b) => byCodeUnits(a.key, b.key)), named: owners };
}

function readOverrides(file) {
  let overrides;
  try {
    overrides = JSON.parse(readFileSync(file, "utf8"));
  } catch (err) {
    throw new GenerateError(`cannot read the overrides ${file}: ${message(err)}`);
  }
  if (!isObject(overrides) || !isObject(overrides.operations)) {
    throw new GenerateError(`${file} must be an object with an "operations" object`);
  }
  for (const key of Object.keys(overrides)) {
    if (key !== "$comment" && key !== "operations") {
      throw new GenerateError(`${file}: unknown top-level key "${key}"`);
    }
  }
  for (const [sdkMethod, override] of Object.entries(overrides.operations)) {
    const where = `${file}: "${sdkMethod}"`;
    if (!SDK_METHOD_PATTERN.test(sdkMethod)) {
      throw new GenerateError(`${where} is not an SDK method name`);
    }
    if (!isObject(override)) {
      throw new GenerateError(`${where} must be an object`);
    }
    for (const key of Object.keys(override)) {
      if (!OVERRIDE_FIELDS.has(key)) {
        throw new GenerateError(
          `${where}: unknown field "${key}" (allowed: ${[...OVERRIDE_FIELDS].join(", ")})`,
        );
      }
    }
    if (typeof override.reason !== "string" || override.reason.trim() === "") {
      throw new GenerateError(`${where}: every override needs a "reason"`);
    }
    if (override.timeoutMs === undefined && override.retry === undefined) {
      throw new GenerateError(`${where}: an override sets "timeoutMs", "retry" or both`);
    }
    if (
      override.timeoutMs !== undefined &&
      (!Number.isInteger(override.timeoutMs) || override.timeoutMs < 1 || override.timeoutMs > MAX_TIMEOUT_MS)
    ) {
      throw new GenerateError(`${where}: "timeoutMs" must be an integer from 1 to ${MAX_TIMEOUT_MS}`);
    }
    // An override only makes retries stricter; a POST that is safe to repeat says so in the document
    // (`x-idempotent-by-design`), where the backend and its reviewers see it too.
    if (override.retry !== undefined && override.retry !== "never") {
      throw new GenerateError(`${where}: "retry" can only be overridden to "never"`);
    }
    if (override.specTask !== undefined && !TASK_ID_PATTERN.test(String(override.specTask))) {
      throw new GenerateError(`${where}: "specTask" must be a task id such as OBE-029`);
    }
  }
  return overrides.operations;
}

/**
 * Applies the reviewed overrides. An override for a method the document does not have yet is allowed only with
 * the `specTask` that adds the operation (it applies by itself once that task regenerates the table); any other
 * unknown method is a typo and fails, as does an override for an operation without an SDK method.
 */
function applyOverrides(operations, named, overrides, file) {
  const byMethod = new Map(operations.map((operation) => [operation.sdkMethod, operation]));
  const waiting = [];
  for (const [sdkMethod, override] of Object.entries(overrides)) {
    const operation = byMethod.get(sdkMethod);
    if (operation === undefined) {
      if (named.has(sdkMethod)) {
        throw new GenerateError(
          `${file}: "${sdkMethod}" is x-internal or x-sdk-exclude in the document, so it has no SDK method`,
        );
      }
      if (override.specTask === undefined) {
        throw new GenerateError(
          `${file}: "${sdkMethod}" is not an x-sdk-method of the document; fix the name, or name the "specTask" ` +
            "that adds the operation",
        );
      }
      waiting.push(`${sdkMethod} (${override.specTask})`);
      continue;
    }
    if (override.timeoutMs !== undefined) {
      operation.entry.timeoutMs = override.timeoutMs;
    }
    if (override.retry !== undefined) {
      operation.entry.retry = override.retry;
    }
  }
  return waiting;
}

