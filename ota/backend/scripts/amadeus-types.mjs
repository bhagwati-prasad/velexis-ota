#!/usr/bin/env node
// amadeus-types.mjs: generates the TypeScript types of the Amadeus specifications that the OTA backend calls
// (OADR-0001 point 2, task OBE-017).
//
// Usage (from ota/backend; `pnpm --filter @velexis/ota-backend amadeus:types` runs it):
//   node scripts/amadeus-types.mjs                              # docs/amadeus-api/*.json into src/amadeus/generated
//   node scripts/amadeus-types.mjs --specs <dir> --out <dir>    # other folders (a copy of the layout)
//
// Every `<Name>_v<N>_Version_<x.y>_swagger_specification.json` of the specification folder (the 9 files of
// docs/amadeus-api/, 12 operations) becomes `<name>.ts` in kebab case (FlightOffersSearch → flight-offers-search.ts),
// with the `paths`, `components` and `operations` that openapi-typescript writes, and `index.ts` re-exports each one
// as a namespace (`import type { FlightOffersSearch } from "./generated"`). The inputs are read, never changed; on
// an in-memory copy:
//
//   - a local `$ref` that points nowhere becomes the empty schema (`unknown`), as in the stub's request validation:
//     Flight Offers Search references the undefined `LoyaltyProgram` and `commissionValue`. The generated file's
//     header lists them. A reference to another file stops the run;
//   - eight files are Swagger 2.0, which openapi-typescript 7 does not read: they are converted to OpenAPI 3.0 with
//     swagger2openapi (`patch`: the small fixes it knows are applied, and anything it cannot fix stops the run
//     instead of producing partial types);
//   - a reference into `#/paths/` is replaced by a copy of its target: Queue List's error schemas point into one of
//     its responses, which openapi-typescript would turn into an index into `paths` that does not type-check;
//   - Queue List is OpenAPI 3.0 but writes its path key with the method in front, `GET/office/queues/{queue-id}`; the
//     key becomes `/office/queues/{queue-id}` (the method must be one the path item defines). Any other path key that
//     does not start with `/` stops the run. Operation ids stay as the specifications write them (Queue List's is
//     `GET/office/queues/{queue-id}`, Flight Create Orders' `createFligtOrders`).
//
// The output is deterministic: no timestamps, no absolute paths, the specifications in file-name order and every
// document passed to openapi-typescript as the same object on every run. Files are written only when their content
// changes, and a `.ts` file of the output folder that no specification produces any more is removed (README.md
// stays). The output is committed, ESLint and Prettier skip the folder, and `git diff --exit-code` after a second run
// proves it is current; never edit it by hand.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import openapiTS, { astToString } from "openapi-typescript";
import swagger2openapi from "swagger2openapi";

const PACKAGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO_ROOT = path.resolve(PACKAGE_DIR, "..", "..");
const USAGE = "usage: node scripts/amadeus-types.mjs [--specs <dir>] [--out <dir>]";

/** First line of every generated file. */
const GENERATED_HEADER = "// Generated by scripts/amadeus-types.mjs — do not edit";
const REGENERATE = "// Regenerate with `pnpm --filter @velexis/ota-backend amadeus:types`.";

/** The file names of docs/amadeus-api/: the API name, its major version and the specification's version. */
const SPEC_FILE = /^([A-Z][A-Za-z0-9]*)_v(\d+)_Version_(\d+(?:\.\d+)*)_swagger_specification\.json$/;

/** The HTTP methods of an OpenAPI path item. */
const HTTP_METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

/** A path key with the method written in front of the path (`GET/office/queues/{queue-id}`). */
const METHOD_PREFIXED_PATH = /^([A-Za-z]+)(\/.*)$/;

class GenerateError extends Error {}

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
const message = (err) => (err instanceof Error ? err.message : String(err));
/** A path relative to the repository root with forward slashes, so the output is the same on every machine. */
const repoPath = (file) => path.relative(REPO_ROOT, file).split(path.sep).join("/");

function readOptions(argv) {
  try {
    const { values } = parseArgs({
      args: argv,
      options: { specs: { type: "string" }, out: { type: "string" } },
      strict: true,
    });
    return {
      specs: path.resolve(values.specs ?? path.join(REPO_ROOT, "docs", "amadeus-api")),
      out: path.resolve(values.out ?? path.join(PACKAGE_DIR, "src", "amadeus", "generated")),
    };
  } catch (err) {
    throw new GenerateError(`${message(err)}\n${USAGE}`);
  }
}

/** `FlightOffersSearch` → `flight-offers-search`. */
function kebabCase(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

/** The specifications of `dir`, in file-name order: `{ file, api, module }`. Any other JSON file stops the run. */
function listSpecifications(dir) {
  if (!existsSync(dir)) {
    throw new GenerateError(`the specification folder ${repoPath(dir)} does not exist`);
  }
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort();
  if (files.length === 0) {
    throw new GenerateError(`the specification folder ${repoPath(dir)} has no .json file`);
  }
  const modules = new Map();
  return files.map((name) => {
    const match = SPEC_FILE.exec(name);
    if (match === null) {
      throw new GenerateError(
        `${name}: not a "<Name>_v<N>_Version_<x.y>_swagger_specification.json" specification file`,
      );
    }
    const api = match[1];
    const module = kebabCase(api);
    if (modules.has(module)) {
      throw new GenerateError(`${name} and ${modules.get(module)} would both generate ${module}.ts`);
    }
    modules.set(module, name);
    return { file: path.join(dir, name), api, module };
  });
}

const unescapePointer = (segment) => segment.replaceAll("~1", "/").replaceAll("~0", "~");

/** The segments of a local `$ref` (`#/definitions/A~1B` → `["definitions", "A/B"]`), or `undefined` for any other. */
function refSegments(ref) {
  if (!ref.startsWith("#/")) {
    return undefined;
  }
  try {
    return ref
      .slice(2)
      .split("/")
      .map((raw) => unescapePointer(decodeURIComponent(raw)));
  } catch {
    return undefined;
  }
}

/** The value a local `$ref` points at in `document`, or `undefined` when it points nowhere. */
function target(document, ref) {
  const segments = refSegments(ref);
  if (segments === undefined) {
    return undefined;
  }
  let current = document;
  for (const segment of segments) {
    if ((!isObject(current) && !Array.isArray(current)) || !Object.hasOwn(current, segment)) {
      return undefined;
    }
    current = current[segment];
  }
  return current;
}

/** A deep copy of `value` in which `replace` may swap any object (it returns `undefined` to keep and walk it). */
function mapObjects(value, replace) {
  if (Array.isArray(value)) {
    return value.map((item) => mapObjects(item, replace));
  }
  if (!isObject(value)) {
    return value;
  }
  const replaced = replace(value);
  if (replaced !== undefined) {
    return replaced;
  }
  return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, mapObjects(child, replace)]));
}

/**
 * The document with every local `$ref` that points nowhere replaced by the empty schema `{}` (typed `unknown`), as
 * the stub's request validation does (tools/amadeus-stub/src/validate.ts): Flight Offers Search references the
 * undefined `LoyaltyProgram` and `commissionValue`. A reference to another file stops the run. The replaced
 * references are listed in the generated file's header, so nothing is dropped silently.
 */
function replaceDanglingRefs(document, where) {
  const dangling = new Set();
  const copy = mapObjects(document, (object) => {
    const ref = object.$ref;
    if (typeof ref !== "string") {
      return undefined;
    }
    if (!ref.startsWith("#/")) {
      throw new GenerateError(`${where}: the reference "${ref}" points outside the document`);
    }
    if (target(document, ref) !== undefined) {
      return undefined;
    }
    dangling.add(ref);
    return {};
  });
  return { document: copy, dangling: [...dangling].sort() };
}

/** The OpenAPI 3 document of a Swagger 2.0 specification, converted in memory. */
async function convertSwagger(document, where) {
  let converted;
  try {
    converted = await swagger2openapi.convertObj(document, { patch: true, warnOnly: false });
  } catch (err) {
    throw new GenerateError(`${where}: swagger2openapi cannot convert it: ${message(err)}`);
  }
  if (!isObject(converted) || !isObject(converted.openapi)) {
    throw new GenerateError(`${where}: swagger2openapi returned no OpenAPI document`);
  }
  return converted.openapi;
}

/**
 * The document with every reference into `#/paths/` replaced by a copy of what it points at. Queue List's error
 * schemas point into a response of its path item (`#/paths/GET~1office~1queues~1%7Bqueue-id%7D/get/responses/500/…`),
 * which openapi-typescript turns into an index into `paths` that does not type-check, and which the renamed path key
 * would break anyway. A reference that points back into itself stops the run.
 */
function inlinePathRefs(document, where) {
  const inline = (value, seen) =>
    mapObjects(value, (object) => {
      const ref = object.$ref;
      if (typeof ref !== "string" || refSegments(ref)?.[0] !== "paths") {
        return undefined;
      }
      if (seen.includes(ref)) {
        throw new GenerateError(`${where}: the reference "${ref}" points back into itself`);
      }
      return inline(target(document, ref), [...seen, ref]);
    });
  return inline(document, []);
}

/**
 * The document with every path key starting with `/`: a key written with its method in front
 * (`GET/office/queues/{queue-id}`) loses the method, which must be one the path item defines. References into the
 * path items are inlined first (`inlinePathRefs`).
 */
function normalisePaths(document, where) {
  if (!isObject(document.paths)) {
    throw new GenerateError(`${where}: the document has no "paths"`);
  }
  const inlined = inlinePathRefs(document, where);
  const paths = {};
  for (const [key, item] of Object.entries(inlined.paths)) {
    let route = key;
    if (!key.startsWith("/")) {
      const match = METHOD_PREFIXED_PATH.exec(key);
      const method = match?.[1]?.toLowerCase();
      if (
        match === null ||
        !HTTP_METHODS.includes(method) ||
        !isObject(item) ||
        !Object.hasOwn(item, method)
      ) {
        throw new GenerateError(`${where}: the path key "${key}" does not start with "/"`);
      }
      route = match[2];
    }
    if (Object.hasOwn(paths, route)) {
      throw new GenerateError(`${where}: the path "${route}" is defined twice`);
    }
    paths[route] = item;
  }
  return { ...inlined, paths };
}

/** The OpenAPI 3 document of one specification file, ready for openapi-typescript. */
async function readSpecification(spec) {
  const where = repoPath(spec.file);
  let document;
  try {
    document = JSON.parse(readFileSync(spec.file, "utf8"));
  } catch (err) {
    throw new GenerateError(`cannot parse ${where}: ${message(err)}`);
  }
  if (!isObject(document)) {
    throw new GenerateError(`${where} is not a JSON object`);
  }
  const { document: complete, dangling } = replaceDanglingRefs(document, where);
  if (complete.swagger === "2.0") {
    return {
      document: normalisePaths(await convertSwagger(complete, where), where),
      format: "Swagger 2.0, converted to OpenAPI 3.0 in memory with swagger2openapi",
      dangling,
    };
  }
  if (typeof complete.openapi === "string" && complete.openapi.startsWith("3.")) {
    return { document: normalisePaths(complete, where), format: `OpenAPI ${complete.openapi}`, dangling };
  }
  throw new GenerateError(`${where} is neither Swagger 2.0 nor OpenAPI 3`);
}

/** The types of one specification, as openapi-typescript writes them, after the header. */
async function generateTypes(spec) {
  const { document, format, dangling } = await readSpecification(spec);
  let ast;
  try {
    ast = await openapiTS(document, { silent: true });
  } catch (err) {
    throw new GenerateError(`openapi-typescript failed on ${repoPath(spec.file)}: ${message(err)}`);
  }
  return [
    GENERATED_HEADER,
    `// Source: ${repoPath(spec.file)} (${format}; openapi-typescript).`,
    ...(dangling.length === 0
      ? []
      : [
          `// References that point nowhere in the specification, typed \`unknown\`: ${dangling.join(", ")}.`,
        ]),
    REGENERATE,
    "",
    astToString(ast),
  ].join("\n");
}

/** `index.ts`: every specification's types as one namespace, named after its API. */
function indexFile(specs) {
  return [
    GENERATED_HEADER,
    `// The types of the ${specs.length} Amadeus specifications, one namespace each:`,
    '//   import type { FlightOffersSearch } from "./generated";',
    '//   type Body = FlightOffersSearch.components["schemas"]["GetFlightOffersQuery"];',
    REGENERATE,
    "",
    ...specs.map((spec) => `export type * as ${spec.api} from "./${spec.module}";`),
    "",
  ].join("\n");
}

/** Writes a file only when its content changes, and says which files changed. */
function writeOutput(out, name, content) {
  const file = path.join(out, name);
  const text = content.endsWith("\n") ? content : `${content}\n`;
  const unchanged = existsSync(file) && readFileSync(file, "utf8") === text;
  if (!unchanged) {
    writeFileSync(file, text);
  }
  console.log(`amadeus:types: ${unchanged ? "unchanged" : "wrote"} ${name}`);
}

async function main(argv) {
  const { specs: specDir, out } = readOptions(argv);
  const specs = listSpecifications(specDir);
  // Every file is generated before anything is written, so a failing specification leaves the folder as it was.
  const outputs = [];
  for (const spec of specs) {
    outputs.push([`${spec.module}.ts`, await generateTypes(spec)]);
  }
  outputs.push(["index.ts", indexFile(specs)]);
  mkdirSync(out, { recursive: true });
  for (const [name, content] of outputs) {
    writeOutput(out, name, content);
  }
  const expected = new Set(outputs.map(([name]) => name));
  for (const name of readdirSync(out).sort()) {
    if (name.endsWith(".ts") && !expected.has(name)) {
      rmSync(path.join(out, name));
      console.log(`amadeus:types: removed ${name}`);
    }
  }
}

main(process.argv.slice(2)).catch((err) => {
  console.error(`amadeus:types: ${err instanceof GenerateError ? err.message : (err?.stack ?? String(err))}`);
  process.exitCode = 1;
});
